// Command ssmagentgen derives the private agent health request from the official
// amazon-ssm-agent SDK source. Public SSM operations remain Smithy-generated.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"strconv"
)

func main() {
	source := flag.String("source", "", "Official amazon-ssm-agent extra/aws-sdk-go/service/ssm/api.go")
	output := flag.String("out", "internal/services/ssmcommands/agent_api_generated.go", "Generated contract output")
	check := flag.Bool("check", false, "compare generated bytes without writing")
	flag.Parse()
	if err := generate(*source, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func generate(source, output string, check bool) error {
	raw, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	file, err := parser.ParseFile(token.NewFileSet(), source, raw, 0)
	if err != nil {
		return err
	}
	var fields []*ast.Field
	ast.Inspect(file, func(n ast.Node) bool {
		decl, ok := n.(*ast.TypeSpec)
		if !ok || decl.Name.Name != "UpdateInstanceInformationInput" {
			return true
		}
		shape, ok := decl.Type.(*ast.StructType)
		if ok {
			fields = shape.Fields.List
		}
		return false
	})
	if len(fields) == 0 {
		return fmt.Errorf("official UpdateInstanceInformationInput shape not found")
	}
	var out, validation, auditFields, auditValues, auditRedactions bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by ssmagentgen from official amazon-ssm-agent extra/aws-sdk-go/service/ssm/api.go; DO NOT EDIT.\n// Source SHA256: %x\npackage ssmcommands\n\n", sha256.Sum256(raw))
	out.WriteString("// UpdateInstanceInformationInput is the agent-private JSON1.1 request, absent from the public Smithy model.\ntype UpdateInstanceInformationInput struct {\n")
	validation.WriteString("func (in *UpdateInstanceInformationInput) validate() error {\n")
	for _, field := range fields {
		if len(field.Names) != 1 || field.Names[0].Name == "_" {
			continue
		}
		name := field.Names[0].Name
		ptr, ok := field.Type.(*ast.StarExpr)
		if !ok {
			return fmt.Errorf("unsupported private shape member %s", name)
		}
		ident, ok := ptr.X.(*ast.Ident)
		if !ok || ident.Name != "string" {
			return fmt.Errorf("unsupported private shape member type %s", name)
		}
		tagText, err := strconv.Unquote(field.Tag.Value)
		if err != nil {
			return err
		}
		tag := reflect.StructTag(tagText)
		fmt.Fprintf(&out, "%s *string `json:%q`\n", name, name+",omitempty")
		auditName := name
		if name[0] >= 'A' && name[0] <= 'Z' {
			auditName = string(name[0]+('a'-'A')) + name[1:]
		}
		fmt.Fprintf(&auditFields, "%s *string `json:%q`\n", name, auditName+",omitempty")
		if tag.Get("sensitive") == "true" {
			fmt.Fprintf(&auditRedactions, "redacted%s := in.%s\nif redacted%s != nil { redacted%s = new(\"HIDDEN_DUE_TO_SECURITY_REASONS\") }\n", name, name, name, name)
			fmt.Fprintf(&auditValues, "%s: redacted%s,\n", name, name)
		} else {
			fmt.Fprintf(&auditValues, "%s: in.%s,\n", name, name)
		}
		if tag.Get("required") == "true" {
			fmt.Fprintf(&validation, "if in.%s==nil{return failure(\"ValidationException\",%q)}\n", name, name+" is required.")
		}
		if minimum := tag.Get("min"); minimum != "" {
			n, err := strconv.Atoi(minimum)
			if err != nil {
				return err
			}
			fmt.Fprintf(&validation, "if in.%s!=nil&&len(*in.%s)<%d{return failure(\"ValidationException\",%q)}\n", name, name, n, name+" is shorter than the required minimum.")
		}
	}
	out.WriteString("}\n")
	validation.WriteString("return nil\n}\n")
	out.Write(validation.Bytes())
	out.WriteString("\n// auditParameters preserves private SDK field presence with the native CloudTrail\n// member casing and sensitive-value marker; it does not alter the wire request.\nfunc (in UpdateInstanceInformationInput) auditParameters() any {\n")
	out.Write(auditRedactions.Bytes())
	out.WriteString("return struct {\n")
	out.Write(auditFields.Bytes())
	out.WriteString("}{\n")
	out.Write(auditValues.Bytes())
	out.WriteString("}\n}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, formatted) {
			return fmt.Errorf("generated private SSM contract differs: %s", output)
		}
		return nil
	}
	return os.WriteFile(output, formatted, 0644)
}
