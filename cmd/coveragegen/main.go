// Command coveragegen records the selected services' Smithy operation inventory
// alongside default-stack registrations. It makes no network calls.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

type options struct {
	SDK, Services, Out string
	Check              bool
}

func main() {
	var o options
	flag.StringVar(&o.SDK, "sdk", "clones/aws-sdk-go-v2", "local AWS SDK for Go v2 checkout")
	flag.StringVar(&o.Services, "services", "docs/service-targets.json", "explicit service and Smithy model selection")
	flag.StringVar(&o.Out, "out", "docs/services.json", "generated operation inventory")
	flag.BoolVar(&o.Check, "check", false, "compare generated bytes without writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "coveragegen: unexpected positional arguments")
		os.Exit(2)
	}
	if err := run(o); err != nil {
		fmt.Fprintln(os.Stderr, "coveragegen:", err)
		os.Exit(1)
	}
}

func run(o options) error {
	inventory, err := readCoverage(o.SDK, o.Services)
	if err != nil {
		return err
	}
	if err := observeStack(&inventory); err != nil {
		return err
	}
	data, err := json.MarshalIndent(inventory, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	current, err := os.ReadFile(o.Out)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if bytes.Equal(current, data) {
		return nil
	}
	if o.Check {
		return fmt.Errorf("generated coverage differs: %s; run go run ./cmd/coveragegen -sdk %q -services %q -out %q", o.Out, o.SDK, o.Services, o.Out)
	}
	if err := os.MkdirAll(filepath.Dir(o.Out), 0o755); err != nil {
		return err
	}
	return writeAtomic(o.Out, data)
}

func writeAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".coveragegen-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(0o644); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
