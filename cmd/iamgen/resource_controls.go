package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

func renderResourceControls(reference sourceSnapshot, path string) ([]byte, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var source struct {
		Source          string   `json:"source"`
		Services        []string `json:"services"`
		ExcludedActions []string `json:"excluded_actions"`
	}
	if err := json.Unmarshal(data, &source); err != nil {
		return nil, err
	}
	if len(source.Services) == 0 {
		return nil, fmt.Errorf("RCP source contains no services")
	}
	slices.Sort(source.Services)
	slices.Sort(source.ExcludedActions)
	services := make(map[string]bool, len(source.Services))
	for _, service := range source.Services {
		services[strings.ToLower(service)] = true
	}
	excluded := make(map[string]bool, len(source.ExcludedActions))
	for _, action := range source.ExcludedActions {
		excluded[strings.ToLower(action)] = true
	}
	var actions []string
	for _, service := range reference.Services {
		prefix := strings.ToLower(service.Name)
		if !services[prefix] {
			continue
		}
		delete(services, prefix)
		for _, action := range service.Actions {
			name := prefix + ":" + strings.ToLower(action.Name)
			// AWS applies RCPs to the resources authorized by the action,
			// not every action in an eligible service's namespace.
			if len(action.Resources) != 0 && !excluded[name] {
				actions = append(actions, name)
			}
		}
	}
	if len(services) != 0 {
		var missing []string
		for service := range services {
			missing = append(missing, service)
		}
		slices.Sort(missing)
		return nil, fmt.Errorf("RCP services missing from AWS service reference: %s", strings.Join(missing, ", "))
	}
	slices.Sort(actions)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by iamgen from data/resource_control_source.json; DO NOT EDIT.")
	fmt.Fprintln(&out, "// Source: "+source.Source)
	fmt.Fprintln(&out, "// Action resources: "+reference.Source+" (captured "+reference.RetrievedAt+")")
	fmt.Fprintln(&out, "package catalog\n\nimport \"strings\"")
	fmt.Fprintln(&out, "// SupportsResourceControlPolicy reports AWS's published RCP service coverage.")
	fmt.Fprintln(&out, "func SupportsResourceControlPolicy(service string) bool { return resourceControlServices[strings.ToLower(service)] }")
	fmt.Fprintln(&out, "// AppliesResourceControlPolicy selects actions with resource types in AWS's service authorization reference.")
	fmt.Fprintln(&out, "// Published action exceptions are excluded; resource-owner exemptions remain service-owned.")
	fmt.Fprintln(&out, "func AppliesResourceControlPolicy(action string) bool { return resourceControlActions[strings.ToLower(action)] }")
	fmt.Fprintln(&out, "var resourceControlServices = map[string]bool{")
	for _, service := range slices.Compact(source.Services) {
		fmt.Fprintf(&out, "%q:true,\n", strings.ToLower(service))
	}
	fmt.Fprintln(&out, "}\nvar resourceControlActions = map[string]bool{")
	for _, action := range slices.Compact(actions) {
		fmt.Fprintf(&out, "%q:true,\n", action)
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}
