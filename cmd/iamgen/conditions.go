package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

func renderConditionTypes(source sourceSnapshot) ([]byte, error) {
	types := make(map[string]map[string]bool)
	for _, service := range source.Services {
		for _, key := range service.ConditionKeys {
			name := strings.ToLower(key.Name)
			if types[name] == nil {
				types[name] = make(map[string]bool)
			}
			for _, sourceType := range key.Types {
				var kind string
				switch strings.TrimPrefix(sourceType, "ArrayOf") {
				case "String", "ARN":
					kind = "string"
				case "Numeric":
					kind = "numeric"
				case "Bool":
					kind = "boolean"
				case "Date":
					kind = "date"
				case "IPAddress":
					kind = "ip"
				default:
					return nil, fmt.Errorf("condition key %s has unknown type %q", key.Name, sourceType)
				}
				if strings.HasPrefix(sourceType, "ArrayOf") {
					kind += "List"
				}
				types[name][kind] = true
			}
		}
	}
	var output bytes.Buffer
	output.WriteString("// Code generated by iamgen from the pinned AWS service reference; DO NOT EDIT.\n\npackage catalog\n\nvar conditionTypes = map[string]string{\n")
	var names []string
	for name := range types {
		names = append(names, name)
	}
	for _, name := range sortedUnique(names) {
		// Overloaded definitions do not establish a type for every operation.
		// Retain them in the source snapshot rather than guessing cardinality.
		if len(types[name]) != 1 {
			continue
		}
		for kind := range types[name] {
			fmt.Fprintf(&output, "%q: %q,\n", name, kind)
		}
	}
	output.WriteString("}\n")
	return format.Source(output.Bytes())
}
