package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

func renderLastAccess(source sourceSnapshot, servicesPath string) ([]byte, error) {
	var actions []string
	for _, service := range source.Services {
		for _, action := range service.Actions {
			if action.SupportedBy["IAM Action Last Accessed"] {
				actions = append(actions, strings.ToLower(service.Name+":"+action.Name))
			}
		}
	}
	slices.Sort(actions)
	actions = slices.Compact(actions)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by iamgen from data/service_reference.json.gz; DO NOT EDIT.")
	fmt.Fprintln(&out, "package catalog\n\nimport \"strings\"")
	fmt.Fprintln(&out, "// TracksActionLastAccess reports AWS's published IAM action-last-access support.")
	fmt.Fprintln(&out, "func TracksActionLastAccess(action string) bool { return trackedLastAccessActions[strings.ToLower(action)] }")
	fmt.Fprintln(&out, "var trackedLastAccessActions = map[string]bool{")
	for _, action := range actions {
		fmt.Fprintf(&out, "%q: true,\n", action)
	}
	fmt.Fprintln(&out, "}")
	namesData, err := os.ReadFile(servicesPath)
	if err != nil {
		return nil, err
	}
	type serviceMetadata struct {
		Namespace     string  `json:"namespace"`
		Name          string  `json:"name"`
		DefaultRegion *string `json:"default_region"`
		TimeSortRank  *int    `json:"time_sort_rank"`
	}
	var names struct {
		Services []serviceMetadata `json:"services"`
	}
	if err := json.Unmarshal(namesData, &names); err != nil {
		return nil, err
	}
	if len(names.Services) == 0 {
		return nil, fmt.Errorf("report service metadata contains no services")
	}

	slices.SortFunc(names.Services, func(a, b serviceMetadata) int { return strings.Compare(a.Namespace, b.Namespace) })
	fmt.Fprintln(&out, "// LastAccessServiceName returns AWS's report display name for a service namespace.")
	fmt.Fprintln(&out, "func LastAccessServiceName(namespace string) (string,bool) { service,ok:=lastAccessServices[namespace];return service.name,ok }")
	fmt.Fprintln(&out, "// OrganizationsAccessDefaultRegion returns the region reported before any service activity.")
	fmt.Fprintln(&out, "// Absence is preserved; global endpoints alone do not imply a report region.")
	fmt.Fprintln(&out, "func OrganizationsAccessDefaultRegion(namespace string) (string,bool) { service:=lastAccessServices[namespace];return service.defaultRegion,service.hasDefaultRegion }")
	fmt.Fprintln(&out, "// OrganizationsAccessTimeSortRank returns the observed ascending order for equal or absent activity times.")
	fmt.Fprintln(&out, "// Unknown service namespaces return -1.")
	fmt.Fprintln(&out, "func OrganizationsAccessTimeSortRank(namespace string) int { service,ok:=lastAccessServices[namespace];if !ok {return -1};return service.timeSortRank }")
	fmt.Fprintf(&out, "// Report metadata is captured in %s.\n", servicesPath)
	fmt.Fprintln(&out, "var lastAccessServices = map[string]struct {name,defaultRegion string;hasDefaultRegion bool;timeSortRank int}{")
	ranks := make(map[int]bool, len(names.Services))
	for _, service := range names.Services {
		if service.TimeSortRank == nil || *service.TimeSortRank < 0 || *service.TimeSortRank >= len(names.Services) || ranks[*service.TimeSortRank] {
			return nil, fmt.Errorf("report service %s has missing or invalid time sort rank", service.Namespace)
		}
		ranks[*service.TimeSortRank] = true
		fmt.Fprintf(&out, "%q:{name:%q,timeSortRank:%d", service.Namespace, service.Name, *service.TimeSortRank)
		if service.DefaultRegion != nil {
			fmt.Fprintf(&out, ",defaultRegion:%q,hasDefaultRegion:true", *service.DefaultRegion)
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}
