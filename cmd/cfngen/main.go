// Command cfngen derives structural CloudFormation resource contracts from an
// explicitly captured regional AWS registry. Resource commands remain handwritten
// integrations with the real service owners; schemas do not define CRUD effects.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"maps"
	"os"
	"slices"
	"strings"
)

type registry struct {
	Region string `json:"region"`
	Types  map[string]struct {
		Schema           json.RawMessage `json:"schema"`
		DefaultVersionID string          `json:"default_version_id"`
	} `json:"types"`
}
type schema struct {
	TypeName              string                     `json:"typeName"`
	Properties            map[string]json.RawMessage `json:"properties"`
	Definitions           map[string]json.RawMessage `json:"definitions"`
	Required              []string                   `json:"required"`
	CreateOnly            []string                   `json:"createOnlyProperties"`
	ReadOnly              []string                   `json:"readOnlyProperties"`
	PrimaryIdentifier     []string                   `json:"primaryIdentifier"`
	AdditionalIdentifiers [][]string                 `json:"additionalIdentifiers"`
	Tagging               struct {
		Taggable                 bool     `json:"taggable"`
		TagOnCreate              bool     `json:"tagOnCreate"`
		TagUpdatable             bool     `json:"tagUpdatable"`
		CloudFormationSystemTags bool     `json:"cloudFormationSystemTags"`
		TagProperty              string   `json:"tagProperty"`
		Permissions              []string `json:"permissions"`
	} `json:"tagging"`
	Handlers map[string]struct {
		Permissions []string `json:"permissions"`
	} `json:"handlers"`
}
type objectNode struct {
	Ref                  string                     `json:"$ref"`
	Properties           map[string]json.RawMessage `json:"properties"`
	Required             []string                   `json:"required"`
	AdditionalProperties json.RawMessage            `json:"additionalProperties"`
	Items                json.RawMessage            `json:"items"`
	MinLength            *int                       `json:"minLength"`
	MaxLength            *int                       `json:"maxLength"`
}

func main() {
	input := flag.String("source", "testdata/aws/cloudformation/resource_schemas.json", "captured regional registry schema source")
	output := flag.String("out", "internal/services/cloudformation/resource_schema_generated.go", "generated contract file")
	check := flag.Bool("check", false, "check committed generated output")
	flag.Parse()
	if err := run(*input, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, "cfngen:", err)
		os.Exit(1)
	}
}
func run(input, output string, check bool) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	var captured registry
	if err = json.Unmarshal(data, &captured); err != nil {
		return err
	}
	if captured.Region == "" || len(captured.Types) == 0 {
		return fmt.Errorf("captured regional resource schemas are required")
	}
	digest := sha256.Sum256(data)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cfngen from the AWS CloudFormation registry; DO NOT EDIT.\n// Source: %s; region %s; SHA256 %s\npackage cloudformation\n\nvar resourceSchemas = map[string]resourceSchema{\n", input, captured.Region, hex.EncodeToString(digest[:]))
	for _, name := range slices.Sorted(maps.Keys(captured.Types)) {
		row := captured.Types[name]
		var s schema
		if err = json.Unmarshal(row.Schema, &s); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if s.TypeName != name || len(s.Properties) == 0 {
			return fmt.Errorf("%s: invalid schema identity/properties", name)
		}
		fmt.Fprintf(&b, "%q: {Version:%q, Properties: []string{", name, row.DefaultVersionID)
		writeStrings(&b, slices.Sorted(maps.Keys(s.Properties)))
		b.WriteString("}, Required: []string{")
		slices.Sort(s.Required)
		writeStrings(&b, s.Required)
		b.WriteString("}, CreateOnly: []string{")
		slices.Sort(s.CreateOnly)
		writeStrings(&b, s.CreateOnly)
		b.WriteString("}, ReadOnly: []string{")
		slices.Sort(s.ReadOnly)
		writeStrings(&b, s.ReadOnly)
		b.WriteString("}, PrimaryIdentifier: []string{")
		writeStrings(&b, s.PrimaryIdentifier)
		b.WriteString("}, AdditionalIdentifiers: [][]string{")
		for _, paths := range s.AdditionalIdentifiers {
			b.WriteString("{")
			writeStrings(&b, paths)
			b.WriteString("},")
		}
		b.WriteString("}, Objects: map[string]resourceObjectSchema{")
		var lengths strings.Builder
		if err := writeObjects(&b, &lengths, s, "/properties", row.Schema, nil); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		b.WriteString("}, StringLengths: map[string]resourceStringLength{")
		b.WriteString(lengths.String())
		fmt.Fprintf(&b, "}, Tagging: resourceTaggingSchema{Taggable:%t, TagOnCreate:%t, TagUpdatable:%t, CloudFormationSystemTags:%t, TagProperty:%q, Permissions:[]string{", s.Tagging.Taggable, s.Tagging.TagOnCreate, s.Tagging.TagUpdatable, s.Tagging.CloudFormationSystemTags, s.Tagging.TagProperty)
		slices.Sort(s.Tagging.Permissions)
		writeStrings(&b, s.Tagging.Permissions)
		b.WriteString("}}, HandlerPermissions:map[string][]string{")
		for _, handler := range slices.Sorted(maps.Keys(s.Handlers)) {
			fmt.Fprintf(&b, "%q:{", handler)
			permissions := s.Handlers[handler].Permissions
			slices.Sort(permissions)
			writeStrings(&b, permissions)
			b.WriteString("},")
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	rendered, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	if check {
		existing, e := os.ReadFile(output)
		if e != nil {
			return e
		}
		if !bytes.Equal(existing, rendered) {
			return fmt.Errorf("generated resource contracts differ: %s", output)
		}
		return nil
	}
	return os.WriteFile(output, rendered, 0644)
}
func writeStrings(b *strings.Builder, values []string) {
	for _, value := range values {
		fmt.Fprintf(b, "%q,", value)
	}
}

func writeObjects(b, lengths *strings.Builder, s schema, path string, raw json.RawMessage, refs []string) error {
	var node objectNode
	if err := json.Unmarshal(raw, &node); err != nil {
		return err
	}
	if node.Ref != "" {
		if !strings.HasPrefix(node.Ref, "#/definitions/") || slices.Contains(refs, node.Ref) {
			return fmt.Errorf("unsupported recursive/external schema reference %s", node.Ref)
		}
		definition, ok := s.Definitions[strings.TrimPrefix(node.Ref, "#/definitions/")]
		if !ok {
			return fmt.Errorf("missing schema reference %s", node.Ref)
		}
		return writeObjects(b, lengths, s, path, definition, append(refs, node.Ref))
	}
	if node.MinLength != nil || node.MaxLength != nil {
		minimum, maximum := 0, -1
		if node.MinLength != nil {
			minimum = *node.MinLength
		}
		if node.MaxLength != nil {
			maximum = *node.MaxLength
		}
		fmt.Fprintf(lengths, "%q:{Min:%d, Max:%d},", path, minimum, maximum)
	}
	if node.Properties != nil {
		fmt.Fprintf(b, "%q:{Properties:[]string{", path)
		writeStrings(b, slices.Sorted(maps.Keys(node.Properties)))
		b.WriteString("}, Required:[]string{")
		slices.Sort(node.Required)
		writeStrings(b, node.Required)
		fmt.Fprintf(b, "}, AdditionalProperties:%t},", string(node.AdditionalProperties) != "false")
		for _, name := range slices.Sorted(maps.Keys(node.Properties)) {
			escaped := strings.ReplaceAll(strings.ReplaceAll(name, "~", "~0"), "/", "~1")
			if err := writeObjects(b, lengths, s, path+"/"+escaped, node.Properties[name], refs); err != nil {
				return err
			}
		}
	}
	if len(node.Items) != 0 {
		return writeObjects(b, lengths, s, path+"/*", node.Items, refs)
	}
	return nil
}
