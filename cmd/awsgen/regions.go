package main

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"slices"
)

// Smithy endpoint rules do not describe token compatibility. This is the owned
// EC2 DescribeRegions response; opt-in status distinguishes the two region sets.
//
//go:embed regions.json
var regionCapture []byte

func renderRegionCompatibility(partitions []byte, revision string) ([]byte, error) {
	var endpoints struct {
		Partitions []struct {
			ID          string
			RegionRegex string
			Regions     map[string]struct{ Description string }
		}
	}
	if err := json.Unmarshal(partitions, &endpoints); err != nil {
		return nil, err
	}
	descriptions := make(map[string]string)
	regionalPartitions := make(map[string]string)
	for _, partition := range endpoints.Partitions {
		regional, err := regexp.Compile(partition.RegionRegex)
		if err != nil {
			return nil, fmt.Errorf("SDK partition %s region pattern: %w", partition.ID, err)
		}
		for name, region := range partition.Regions {
			if region.Description == "" {
				return nil, fmt.Errorf("SDK region %s has no description", name)
			}
			descriptions[name] = region.Description
			if regional.MatchString(name) {
				regionalPartitions[name] = partition.ID
			}
		}
	}
	var capture struct {
		ObservedAt string `json:"observed_at"`
		Regions    []struct{ RegionName, OptInStatus string }
	}
	if err := json.Unmarshal(regionCapture, &capture); err != nil {
		return nil, err
	}
	var names, optIn []string
	for _, region := range capture.Regions {
		switch region.OptInStatus {
		case "opt-in-not-required":
			names = append(names, region.RegionName)
		case "opted-in", "not-opted-in":
			optIn = append(optIn, region.RegionName)
		default:
			return nil, fmt.Errorf("unknown opt-in status %q for %s", region.OptInStatus, region.RegionName)
		}
	}
	slices.Sort(names)
	slices.Sort(optIn)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by awsgen from AWS EC2 DescribeRegions and SDK endpoints; DO NOT EDIT.")
	fmt.Fprintf(&out, "// Source: cmd/awsgen/regions.json, observed %s\n", capture.ObservedAt)
	fmt.Fprintf(&out, "// Region descriptions: aws-sdk-go-v2/internal/endpoints/awsrulesfn/partitions.json at %s\n", revision)
	fmt.Fprintln(&out, "package awscatalog")
	fmt.Fprintln(&out, "// CommercialRegion describes the captured commercial region catalogue.")
	fmt.Fprintln(&out, "type CommercialRegion struct { Name string; OptInRequired bool }")
	fmt.Fprintln(&out, "// CommercialRegions returns a detached, name-ordered region catalogue.")
	fmt.Fprintln(&out, "func CommercialRegions() []CommercialRegion { return []CommercialRegion{")
	all := append(slices.Clone(names), optIn...)
	slices.Sort(all)
	for _, name := range all {
		fmt.Fprintf(&out, "{Name: %q, OptInRequired: %t},\n", name, slices.Contains(optIn, name))
	}
	fmt.Fprintln(&out, "} }")
	fmt.Fprintln(&out, "// CommercialRegionRequiresOptIn reports captured commercial opt-in regions; unknown regions return false.")
	fmt.Fprintln(&out, "func CommercialRegionRequiresOptIn(region string) bool { switch region {")
	for _, name := range optIn {
		fmt.Fprintf(&out, "case %q: return true\n", name)
	}
	fmt.Fprintln(&out, "default: return false } }")
	fmt.Fprintln(&out, "// SupportsLegacySTSTokens reports commercial regions enabled by default.")
	fmt.Fprintln(&out, "// Unknown/new regions require modern tokens; partition checks remain separate.")
	fmt.Fprintln(&out, "func SupportsLegacySTSTokens(region string) bool { switch region {")
	for _, name := range names {
		fmt.Fprintf(&out, "case %q: return true\n", name)
	}
	fmt.Fprintln(&out, "default: return false } }")
	fmt.Fprintln(&out, "// RegionPartition identifies SDK-described regional endpoints; global aliases and unknown codes return empty.")
	fmt.Fprintln(&out, "func RegionPartition(region string) string { switch region {")
	for _, name := range sortedKeys(regionalPartitions) {
		fmt.Fprintf(&out, "case %q: return %q\n", name, regionalPartitions[name])
	}
	fmt.Fprintln(&out, "default: return \"\" } }")
	fmt.Fprintln(&out, "// RegionDisplayName returns the SDK endpoint description, or the code for an unknown region.")
	fmt.Fprintln(&out, "func RegionDisplayName(region string) string { switch region {")
	for _, name := range sortedKeys(descriptions) {
		fmt.Fprintf(&out, "case %q: return %q\n", name, descriptions[name])
	}
	fmt.Fprintln(&out, "default: return region } }")
	return format.Source(out.Bytes())
}
