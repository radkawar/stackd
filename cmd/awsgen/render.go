const generatedHeader = "// Code generated by awsgen from AWS SDK for Go v2 Smithy models; DO NOT EDIT.\n"

func renderCatalog(c contract) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	fmt.Fprintf(&out, "// Source: %s at %s; SHA256 %s\n", c.Info.Source.Path, c.Info.Source.Revision, c.Info.Source.SHA256)
	if c.Info.Source.CorrectionsSHA256 != "" {
		fmt.Fprintf(&out, "// Model corrections: %s; SHA256 %s\n", c.Info.Source.CorrectionsPath, c.Info.Source.CorrectionsSHA256)
	}
	fmt.Fprintln(&out, "package awscatalog")
	prefix := exportedName(c.Info.SDKID)
	fmt.Fprintln(&out, "const (")
	for _, op := range c.Operations {
		fmt.Fprintf(&out, "%sOp%s OperationName = %q\n", prefix, op.Name, op.Name)
	}
	fmt.Fprintln(&out, ")")
	return format.Source(out.Bytes())
}

// Service descriptor tables have separate compilation units: combining every
// model in awscatalog exceeds the Go object-file limit under race instrumentation.
func renderServiceMetadata(c contract) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	fmt.Fprintf(&out, "package %s\n\nimport \"stackd/internal/awsschema\"\n\n", c.Info.Name)
	fmt.Fprintf(&out, "var Info = %s\n\nvar Operations = []awsschema.Operation{\n", goLiteral(c.Info))
	for _, op := range c.Operations {
		fmt.Fprintf(&out, "%s,\n", goLiteral(op))
	}
	fmt.Fprintln(&out, "}\n\nvar Shapes = []awsschema.Shape{")
	for _, shape := range c.Shapes {
		fmt.Fprintf(&out, "%s,\n", goLiteral(shape))
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}

func renderIndex(contracts []contract) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	fmt.Fprintln(&out, "package awscatalog\n\nimport (")
	for _, c := range contracts {
		fmt.Fprintf(&out, "%smodel %q\n", c.Info.Name, "stackd/internal/awscatalog/models/"+c.Info.Name)
	}
	fmt.Fprintln(&out, ")\n\nvar catalog = map[string]Service{")
	for _, c := range contracts {
		fmt.Fprintf(&out, "%q: newService(%smodel.Info, %smodel.Operations, %smodel.Shapes),\n", c.Info.Name, c.Info.Name, c.Info.Name, c.Info.Name)
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}

func renderTypes(c contract) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	fmt.Fprintf(&out, "package %s\n\n", c.Info.Name)
	for _, shape := range c.Shapes {
		if shape.Kind == "timestamp" {
			fmt.Fprintln(&out, `import "time"`)
			break
		}
	}
	shapes := map[awsschema.ShapeID]awsschema.Shape{}
	shapeNames := make(map[string]bool, len(c.Shapes))
	for _, shape := range c.Shapes {
		shapes[shape.ID] = shape
		shapeNames[exportedName(shapeName(shape.ID))] = true
	}
	emitted := make(map[string]bool, len(c.Shapes))
	for _, shape := range c.Shapes {
		name := exportedName(shapeName(shape.ID))
		if emitted[name] {
			continue // validateContract permits only equivalent scalar Go types.
		}
		emitted[name] = true
		fmt.Fprintf(&out, "// %s represents Smithy shape %s.\n", name, shape.ID)
		switch shape.Kind {
		case "structure", "union":
			fmt.Fprintf(&out, "type %s struct {\n", name)
			for _, member := range shape.Members {
				if member.Required {
					fmt.Fprintln(&out, "// Required by the AWS service model.")
				}
				jsonName := member.JSONName
				if jsonName == "" {
					jsonName = member.Name
				}
				omit := "omitempty"
				switch shapes[member.Target].Kind {
				case "list", "set", "map", "blob":
					// Present-empty collections must survive typed JSON storage;
					// only nil represents an absent Smithy member.
					omit = "omitzero"
				}
				fmt.Fprintf(&out, "%s %s `json:%q smithy:%q`\n", exportedName(member.Name), memberGoType(member, shapes), jsonName+","+omit, member.Name)
			}
			fmt.Fprintln(&out, "}")
		case "list", "set":
			element := exportedName(shapeName(shape.Member.Target))
			if shape.Sparse {
				element = "*" + element
			}
			fmt.Fprintf(&out, "type %s []%s\n", name, element)
		case "map":
			element := exportedName(shapeName(shape.Value.Target))
			if shape.Sparse {
				element = "*" + element
			}
			fmt.Fprintf(&out, "type %s map[%s]%s\n", name, exportedName(shapeName(shape.Key.Target)), element)
		case "enum", "intEnum":
			base := "string"
			if shape.Kind == "intEnum" {
				base = "int32"
			}
			fmt.Fprintf(&out, "type %s %s\nconst (\n", name, base)
			for _, value := range shape.Enum {
				encoded := strconv.Quote(value.Value)
				if base != "string" {
					encoded = value.Value
				}
				fmt.Fprintf(&out, "%s%s %s = %s\n", name, exportedName(value.Name), name, encoded)
			}
			fmt.Fprintln(&out, ")")
		case "timestamp":
			fmt.Fprintf(&out, "type %s = time.Time\n", name)
		default:
			base := map[awsschema.ShapeKind]string{"string": "string", "blob": "[]byte", "boolean": "bool", "byte": "int8", "short": "int16", "integer": "int32", "long": "int64", "float": "float32", "double": "float64", "document": "any"}[shape.Kind]
			if base == "" {
				return nil, fmt.Errorf("no Go type for %s", shape.Kind)
			}
			fmt.Fprintf(&out, "type %s %s\n", name, base)
		}
	}
	for _, op := range c.Operations {
		for _, item := range []struct {
			suffix string
			id     awsschema.ShapeID
		}{{"Input", op.Input}, {"Output", op.Output}} {
			name, target := string(op.Name)+item.suffix, exportedName(shapeName(item.id))
			// A model can use an operation-style name for a different nested
			// shape. Preserve that shape; aliases never shadow model symbols.
			if !shapeNames[name] {
				fmt.Fprintf(&out, "type %s = %s\n", name, target)
			}
		}
	}
	return format.Source(out.Bytes())
}

func renderDecoder(c contract) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	fmt.Fprintf(&out, "package %s\n\nimport (\n\"fmt\"\n\n\"stackd/internal/awsapi\"\n\"stackd/internal/awscatalog\"\n)\n", c.Info.Name)
	fmt.Fprintln(&out, "// DecodeRequest binds wire input to a generated operation DTO and validates")
	fmt.Fprintln(&out, "// its Smithy constraints. Business logic remains the service provider's responsibility.")
	fmt.Fprintln(&out, "// Known operation metadata is retained on failure; Input is set only after validation.")
	fmt.Fprintln(&out, "func DecodeRequest(operation string, request awsapi.Request) (awsapi.DecodedRequest,error) {")
	fmt.Fprintf(&out, "service, _ := awscatalog.LookupService(%q)\n", c.Info.Name)
	out.WriteString("if request.Protocol != \"\" { service.Protocol = request.Protocol }\n")
	out.WriteString("op, ok := service.Operation(operation)\nif !ok { return awsapi.DecodedRequest{}, fmt.Errorf(\"%w: %s\",awsapi.ErrUnknownOperation,operation) }\ndecoded := awsapi.DecodedRequest{Operation:op,Protocol:service.Protocol,Body:request.Body}\ninput, err := NewInput(operation)\nif err != nil { return decoded,err }\nif err := awsapi.Decode(service,op,request,input); err != nil { return decoded,err }\ndecoded.Input=input\nreturn decoded,nil\n}\n")
	fmt.Fprintln(&out, "// NewInput allocates the generated operation DTO without binding or admitting a request.")
	fmt.Fprintln(&out, "// Error observers may bind rejected input for service-owned, model-redacted audit projection.")
	out.WriteString("func NewInput(operation string) (any,error) {\nswitch operation {\n")
	for _, op := range c.Operations {
		fmt.Fprintf(&out, "case %q:\nreturn new(%s),nil\n", op.Name, exportedName(shapeName(op.Input)))
	}
	out.WriteString("default: return nil,fmt.Errorf(\"%w: %s\",awsapi.ErrUnknownOperation,operation)\n}\n}\n")
	return format.Source(out.Bytes())
}

func memberGoType(member awsschema.Member, shapes map[awsschema.ShapeID]awsschema.Shape) string {
	name := exportedName(shapeName(member.Target))
	if shape := shapes[member.Target]; shape.Kind == "union" && shape.Streaming {
		return "<-chan " + name
	}
	switch shapes[member.Target].Kind {
	case "list", "set", "map", "blob", "document":
		return name
	default:
		return "*" + name
	}
}

func exportedName(name string) string {
	var result strings.Builder
	upper := true
	for _, r := range name {
		if !(unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_') {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		result.WriteRune(r)
	}
	return result.String()
}

// goLiteral emits only our typed descriptor values. Reflection is confined to
// generation, keeping the checked-in catalog ordinary compile-time Go literals.
func goLiteral(value any) string { return literalValue(reflect.ValueOf(value)) }
func literalValue(value reflect.Value) string {
	switch value.Kind() {
	case reflect.String:
		return strconv.Quote(value.String())
	case reflect.Bool:
		return strconv.FormatBool(value.Bool())
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(value.Int(), 10)
	case reflect.Struct:
		var fields []string
		for i := 0; i < value.NumField(); i++ {
			if !value.Field(i).IsZero() {
				fields = append(fields, value.Type().Field(i).Name+":"+literalValue(value.Field(i)))
			}
		}
		return value.Type().String() + "{" + strings.Join(fields, ",") + "}"
	case reflect.Slice:
		values := make([]string, value.Len())
		for i := range values {
			values[i] = literalValue(value.Index(i))
		}
		return "[]" + value.Type().Elem().String() + "{" + strings.Join(values, ",") + "}"
	default:
		panic("unsupported generated literal type: " + value.Type().String())
	}
}
