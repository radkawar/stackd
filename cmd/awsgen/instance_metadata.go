package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

// IMDS has no Smithy model. Native menus and the retained primary category
// reference own vocabulary and release gates; EC2 owns resource values/presence.
func renderInstanceMetadataRoutes(raw []byte) ([]byte, error) {
	var capture struct {
		HTTP []struct {
			Path, Method, Body string
			Token              bool `json:"token_supplied"`
			Code               int
		} `json:"metadata_http"`
		Reference struct {
			Categories []struct {
				Root, Category string
				Introduced     string `json:"introduced_version"`
			}
		} `json:"category_reference"`
	}
	if err := json.Unmarshal(raw, &capture); err != nil {
		return nil, err
	}
	var versions []string
	var notFound string
	metadata, dynamic := map[string][]string{}, map[string][]string{}
	for _, row := range capture.HTTP {
		if row.Method != "GET" || !row.Token {
			continue
		}
		if row.Code == 404 && notFound == "" {
			notFound = row.Body
		}
		if row.Path == "/" && row.Code == 200 {
			versions = strings.Split(row.Body, "\n")
			continue
		}
		version, path, found := strings.Cut(strings.TrimPrefix(row.Path, "/"), "/")
		if !found {
			continue
		}
		switch path {
		case "meta-data/":
			if row.Code == 200 {
				metadata[version] = strings.Split(row.Body, "\n")
			}
		case "dynamic/":
			if row.Code == 200 {
				dynamic[version] = strings.Split(row.Body, "\n")
			} else if row.Code == 404 {
				dynamic[version] = []string{}
			}
		}
	}
	if len(versions) == 0 {
		return nil, fmt.Errorf("native IMDS capture lacks its authenticated version listing")
	}
	if notFound == "" {
		return nil, fmt.Errorf("native IMDS capture lacks its not-found response")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by awsgen from native IMDS observations and AWS category documentation. DO NOT EDIT.\n\npackage ec2")
	fmt.Fprintf(&out, "\nconst instanceMetadataVersionListing = %q\n", strings.Join(versions, "\n"))
	fmt.Fprintf(&out, "\nconst instanceMetadataNotFoundBody = %q\n", notFound)
	for _, directory := range []struct {
		name string
		rows map[string][]string
	}{{"instanceMetadataCategories", metadata}, {"instanceDynamicCategories", dynamic}} {
		nativeCategories := map[string]bool{}
		for _, entries := range directory.rows {
			for _, entry := range entries {
				nativeCategories[strings.TrimSuffix(entry, "/")] = true
			}
		}
		fmt.Fprintf(&out, "\nvar %s = map[string]map[string]bool{\n", directory.name)
		for _, version := range versions {
			entries, ok := directory.rows[version]
			if !ok {
				return nil, fmt.Errorf("native IMDS capture lacks %s for version %s", directory.name, version)
			}
			entries = slices.Clone(entries)
			root := "meta-data"
			if directory.name == "instanceDynamicCategories" {
				root = "dynamic"
			}
			for _, row := range capture.Reference.Categories {
				if row.Root != root || row.Introduced == "" || (version != "latest" && row.Introduced != "1.0" && (version == "1.0" || version < row.Introduced)) {
					continue
				}
				category, _, _ := strings.Cut(row.Category, "/")
				if nativeCategories[category] {
					continue
				}
				if !slices.Contains(entries, category) && !slices.Contains(entries, category+"/") {
					entries = append(entries, category)
				}
			}
			slices.Sort(entries)
			fmt.Fprintf(&out, "%q: {", version)
			for _, entry := range entries {
				if entry != "" {
					fmt.Fprintf(&out, "%q: true,", strings.TrimSuffix(entry, "/"))
				}
			}
			fmt.Fprintln(&out, "},")
		}
		fmt.Fprintln(&out, "}")
	}
	if len(capture.Reference.Categories) == 0 {
		return nil, fmt.Errorf("native IMDS capture lacks its primary category reference")
	}
	// Native top-level menus are conditional: e.g. a private-only guest cannot
	// establish whether public-ipv4 exists in a historical build. Documentation
	// supplies those categories and leaf introduction dates without inventing
	// values for owners the instance does not have.
	introductions := map[string]string{}
	for _, row := range capture.Reference.Categories {
		if row.Introduced == "" {
			continue
		}
		introductions[row.Root+"/"+row.Category] = row.Introduced
	}
	// A successful leaf in an older native build is stronger evidence than a
	// later documentation date (placement/region is one observed example).
	// Conditional 404s cannot establish a category's introduction.
	for _, row := range capture.HTTP {
		if row.Method != "GET" || !row.Token || row.Code != 200 {
			continue
		}
		version, path, _ := strings.Cut(strings.TrimPrefix(row.Path, "/"), "/")
		if version == "latest" {
			continue
		}
		if introduced := introductions[path]; introduced != "" && version < introduced {
			introductions[path] = version
		}
	}
	keys := make([]string, 0, len(introductions))
	for path := range introductions {
		keys = append(keys, path)
	}
	slices.Sort(keys)
	fmt.Fprintln(&out, "\nvar instanceMetadataIntroductions = map[string]string{")
	for _, path := range keys {
		fmt.Fprintf(&out, "%q: %q,\n", path, introductions[path])
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}
