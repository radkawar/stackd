// Command mqschemagen extracts ActiveMQ configuration name membership from the
// retained AWS XSD. It does not validate primitive values or XML serialization.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"io"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const (
	xsdNamespace  = "http://www.w3.org/2001/XMLSchema"
	coreNamespace = "http://activemq.apache.org/schema/core"
	sourceURL     = "https://docs.aws.amazon.com/amazon-mq/latest/developer-guide/samples/amazon-mq-active-mq-5.18.4.xsd.zip"
)

type node struct {
	name       xml.Name
	attrs      map[string]string
	namespaces map[string]string
	children   []*node
}

type element struct {
	attributes map[string]bool
	children   map[string]string
}

type schema struct {
	globals     map[string]*node
	groups      map[string]*node
	simpleTypes map[string]*node
	elements    map[string]*element
}

func main() {
	input := flag.String("schema", "testdata/aws/mq/amazon-mq-active-mq-5.18.4.xsd", "retained AWS ActiveMQ XSD")
	out := flag.String("out", "internal/services/mq/configuration_schema_generated.go", "generated Go file")
	check := flag.Bool("check", false, "compare generated bytes without writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "unexpected positional arguments")
		os.Exit(1)
	}
	if err := run(*input, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, out string, check bool) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	root, err := parse(data)
	if err != nil {
		return err
	}
	s, err := extract(root)
	if err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by mqschemagen; DO NOT EDIT.")
	fmt.Fprintln(&b, "// AWS ActiveMQ schema version: 5.18.4")
	fmt.Fprintf(&b, "// Source: %s\n// Source SHA256: %x\n", sourceURL, sha256.Sum256(data))
	fmt.Fprintln(&b, "// Name membership only; not primitive-value or full XSD validation.")
	fmt.Fprintln(&b, "\npackage mq\n\nvar activeMQSchemaElements = map[string]activeMQSchemaElement{")
	for _, id := range slices.Sorted(maps.Keys(s.elements)) {
		e := s.elements[id]
		fmt.Fprintf(&b, "%q: {\n", id)
		if len(e.attributes) != 0 {
			fmt.Fprintln(&b, "attributes: map[string]bool{")
			for _, name := range slices.Sorted(maps.Keys(e.attributes)) {
				fmt.Fprintf(&b, "%q: true,\n", name)
			}
			fmt.Fprintln(&b, "},")
		}
		if len(e.children) != 0 {
			fmt.Fprintln(&b, "children: map[string]string{")
			for _, name := range slices.Sorted(maps.Keys(e.children)) {
				fmt.Fprintf(&b, "%q: %q,\n", name, e.children[name])
			}
			fmt.Fprintln(&b, "},")
		}
		fmt.Fprintln(&b, "},")
	}
	fmt.Fprintln(&b, "}")
	generated, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(out)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("%s is stale; run go run ./cmd/mqschemagen -schema %q -out %q", out, input, out)
		}
		fmt.Printf("%s is current (%d element contexts)\n", out, len(s.elements))
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(out, generated, 0o644); err != nil {
		return err
	}
	fmt.Printf("Generated %s (%d element contexts)\n", out, len(s.elements))
	return nil
}

// Keep all schema nodes rather than decoding into a lossy struct: an unfamiliar
// membership construct must fail generation instead of silently removing names.
func parse(data []byte) (*node, error) {
	d := xml.NewDecoder(bytes.NewReader(data))
	var root *node
	var stack []*node
	for {
		token, err := d.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		switch t := token.(type) {
		case xml.StartElement:
			n := &node{name: t.Name, attrs: map[string]string{}, namespaces: map[string]string{}}
			if len(stack) != 0 {
				n.namespaces = maps.Clone(stack[len(stack)-1].namespaces)
			}
			seen := map[xml.Name]bool{}
			for _, a := range t.Attr {
				if seen[a.Name] {
					return nil, fmt.Errorf("duplicate attribute %v", a.Name)
				}
				seen[a.Name] = true
				switch {
				case a.Name.Space == "xmlns":
					n.namespaces[a.Name.Local] = a.Value
				case a.Name.Space == "" && a.Name.Local == "xmlns":
					n.namespaces[""] = a.Value
				case a.Name.Space != "":
					return nil, fmt.Errorf("unsupported namespaced schema attribute %v", a.Name)
				default:
					n.attrs[a.Name.Local] = a.Value
				}
			}
			if len(stack) == 0 {
				if root != nil {
					return nil, fmt.Errorf("multiple schema roots")
				}
				root = n
			} else {
				parent := stack[len(stack)-1]
				parent.children = append(parent.children, n)
			}
			stack = append(stack, n)
		case xml.EndElement:
			stack = stack[:len(stack)-1]
		case xml.CharData:
			if strings.TrimSpace(string(t)) != "" {
				return nil, fmt.Errorf("unsupported schema text")
			}
		case xml.Directive:
			return nil, fmt.Errorf("XML directives are unsupported")
		case xml.ProcInst:
			if t.Target != "xml" || root != nil {
				return nil, fmt.Errorf("unsupported processing instruction %q", t.Target)
			}
		}
	}
	if root == nil || len(stack) != 0 {
		return nil, fmt.Errorf("incomplete schema")
	}
	return root, nil
}

func (n *node) validate(kind string, allowed ...string) error {
	if n.name != (xml.Name{Space: xsdNamespace, Local: kind}) {
		return fmt.Errorf("expected xs:%s, got %v", kind, n.name)
	}
	for name := range n.attrs {
		if !slices.Contains(allowed, name) {
			return fmt.Errorf("unsupported xs:%s attribute %q", kind, name)
		}
	}
	if n.attrs["maxOccurs"] == "0" {
		return fmt.Errorf("maxOccurs=0 requires explicit membership handling")
	}
	return nil
}

func (n *node) qname(value string) (xml.Name, error) {
	prefix, local, found := strings.Cut(value, ":")
	if !found {
		prefix, local = "", value
	}
	if local == "" || strings.Contains(local, ":") {
		return xml.Name{}, fmt.Errorf("invalid QName %q", value)
	}
	ns, ok := n.namespaces[prefix]
	if prefix != "" && !ok {
		return xml.Name{}, fmt.Errorf("unbound QName %q", value)
	}
	return xml.Name{Space: ns, Local: local}, nil
}

func extract(root *node) (*schema, error) {
	if err := root.validate("schema", "targetNamespace", "elementFormDefault", "attributeFormDefault"); err != nil {
		return nil, err
	}
	if root.attrs["targetNamespace"] != coreNamespace || root.attrs["elementFormDefault"] != "qualified" {
		return nil, fmt.Errorf("expected qualified ActiveMQ core schema")
	}
	if form := root.attrs["attributeFormDefault"]; form != "" && form != "unqualified" {
		return nil, fmt.Errorf("qualified attributes are unsupported")
	}
	s := &schema{globals: map[string]*node{}, groups: map[string]*node{}, simpleTypes: map[string]*node{}, elements: map[string]*element{}}
	for _, n := range root.children {
		var dst map[string]*node
		switch n.name.Local {
		case "element":
			dst = s.globals
		case "group":
			dst = s.groups
		case "simpleType":
			dst = s.simpleTypes
		default:
			return nil, fmt.Errorf("unsupported schema declaration %v", n.name)
		}
		if n.name.Space != xsdNamespace || n.attrs["name"] == "" {
			return nil, fmt.Errorf("invalid global declaration %v", n.name)
		}
		name := n.attrs["name"]
		if dst[name] != nil {
			return nil, fmt.Errorf("duplicate global %s %q", n.name.Local, name)
		}
		dst[name] = n
	}
	for _, name := range slices.Sorted(maps.Keys(s.simpleTypes)) {
		if err := s.simpleType(s.simpleTypes[name], map[string]bool{name: true}); err != nil {
			return nil, err
		}
	}
	for _, name := range slices.Sorted(maps.Keys(s.globals)) {
		if err := s.declaration(s.globals[name], name); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
	}
	if s.elements["broker"] == nil {
		return nil, fmt.Errorf("schema has no broker declaration")
	}
	return s, nil
}

func (s *schema) declaration(n *node, id string) error {
	if err := n.validate("element", "name", "minOccurs", "maxOccurs"); err != nil {
		return err
	}
	if n.attrs["name"] == "" {
		return fmt.Errorf("element has no name")
	}
	if s.elements[id] != nil {
		return fmt.Errorf("ambiguous element context %q", id)
	}
	e := &element{attributes: map[string]bool{}, children: map[string]string{}}
	s.elements[id] = e
	hasType := false
	for _, child := range n.children {
		switch child.name.Local {
		case "complexType":
			if hasType {
				return fmt.Errorf("multiple element types")
			}
			hasType = true
			if err := child.validate("complexType"); err != nil {
				return err
			}
			for _, member := range child.children {
				if member.name.Local == "attribute" {
					if err := s.attribute(member, e); err != nil {
						return err
					}
				} else if err := s.particle(member, id, e, map[string]bool{}); err != nil {
					return err
				}
			}
		case "key", "unique":
			// Identity constraints affect values, not element/attribute membership.
			if err := child.validate(child.name.Local, "name"); err != nil {
				return err
			}
			for _, field := range child.children {
				if field.name.Local != "selector" && field.name.Local != "field" {
					return fmt.Errorf("unsupported identity constraint %v", field.name)
				}
				if err := field.validate(field.name.Local, "xpath"); err != nil {
					return err
				}
				if len(field.children) != 0 {
					return fmt.Errorf("unexpected identity constraint children")
				}
			}
		default:
			return fmt.Errorf("unsupported element content %v", child.name)
		}
	}
	if !hasType {
		return fmt.Errorf("element %q lacks an explicit supported type", id)
	}
	return nil
}

func (s *schema) particle(n *node, id string, e *element, visiting map[string]bool) error {
	switch n.name.Local {
	case "sequence", "choice", "all":
		if err := n.validate(n.name.Local, "minOccurs", "maxOccurs"); err != nil {
			return err
		}
		for _, child := range n.children {
			if err := s.particle(child, id, e, visiting); err != nil {
				return err
			}
		}
	case "group":
		if err := n.validate("group", "ref", "minOccurs", "maxOccurs"); err != nil {
			return err
		}
		if len(n.children) != 0 {
			return fmt.Errorf("group reference has children")
		}
		ref, err := n.qname(n.attrs["ref"])
		if err != nil {
			return err
		}
		group := s.groups[ref.Local]
		if ref.Space != coreNamespace || group == nil {
			return fmt.Errorf("unresolved group %v", ref)
		}
		if visiting[ref.Local] {
			return fmt.Errorf("cyclic group %q", ref.Local)
		}
		if err := group.validate("group", "name"); err != nil {
			return err
		}
		visiting[ref.Local] = true
		for _, child := range group.children {
			if err := s.particle(child, id, e, visiting); err != nil {
				return err
			}
		}
		delete(visiting, ref.Local)
	case "element":
		if refValue := n.attrs["ref"]; refValue != "" {
			if err := n.validate("element", "ref", "minOccurs", "maxOccurs"); err != nil {
				return err
			}
			if len(n.children) != 0 {
				return fmt.Errorf("element reference has children")
			}
			ref, err := n.qname(refValue)
			if err != nil {
				return err
			}
			if ref.Space != coreNamespace || s.globals[ref.Local] == nil {
				return fmt.Errorf("unresolved element %v", ref)
			}
			return addChild(e, ref.Local, ref.Local)
		}
		childID := id + "/" + n.attrs["name"]
		if err := s.declaration(n, childID); err != nil {
			return err
		}
		return addChild(e, n.attrs["name"], childID)
	case "any":
		if err := n.validate("any", "namespace", "processContents", "minOccurs", "maxOccurs"); err != nil {
			return err
		}
		if len(n.children) != 0 {
			return fmt.Errorf("wildcard has unsupported children")
		}
		if process := n.attrs["processContents"]; process != "" && process != "strict" {
			return fmt.Errorf("unsupported wildcard processContents %q", process)
		}
		// Strict wildcards accept only declared elements. Foreign namespaces are
		// deliberately excluded by the sanitizer's namespace security boundary.
		namespaces := strings.Fields(n.attrs["namespace"])
		if len(namespaces) == 0 {
			namespaces = []string{"##any"}
		}
		includeCore := false
		for _, namespace := range namespaces {
			switch namespace {
			case "##any", "##targetNamespace", coreNamespace:
				includeCore = true
			case "##other", "##local":
			default:
				return fmt.Errorf("unsupported wildcard namespace %q", namespace)
			}
		}
		if includeCore {
			for _, name := range slices.Sorted(maps.Keys(s.globals)) {
				if err := addChild(e, name, name); err != nil {
					return err
				}
			}
		}
	default:
		return fmt.Errorf("unsupported membership particle %v", n.name)
	}
	return nil
}

func addChild(e *element, name, id string) error {
	if previous, ok := e.children[name]; ok && previous != id {
		return fmt.Errorf("conflicting child contexts for %q: %q and %q", name, previous, id)
	}
	e.children[name] = id
	return nil
}

func (s *schema) attribute(n *node, e *element) error {
	if err := n.validate("attribute", "name", "type"); err != nil {
		return err
	}
	name := n.attrs["name"]
	if name == "" || e.attributes[name] {
		return fmt.Errorf("missing or duplicate attribute name %q", name)
	}
	if typeName := n.attrs["type"]; typeName != "" {
		if len(n.children) != 0 {
			return fmt.Errorf("attribute has both named and inline type")
		}
		if err := s.typeReference(n, typeName, map[string]bool{}); err != nil {
			return err
		}
	} else {
		if len(n.children) != 1 {
			return fmt.Errorf("attribute %q lacks one explicit simple type", name)
		}
		if err := s.simpleType(n.children[0], map[string]bool{}); err != nil {
			return err
		}
	}
	e.attributes[name] = true
	return nil
}

func (s *schema) typeReference(n *node, value string, visiting map[string]bool) error {
	ref, err := n.qname(value)
	if err != nil {
		return err
	}
	if ref.Space == xsdNamespace {
		switch ref.Local {
		case "boolean", "double", "integer", "long", "short", "string":
			return nil
		default:
			return fmt.Errorf("unhandled primitive type %q", value)
		}
	}
	typeNode := s.simpleTypes[ref.Local]
	if ref.Space != coreNamespace || typeNode == nil {
		return fmt.Errorf("unresolved simple type %q", value)
	}
	if visiting[ref.Local] {
		return fmt.Errorf("cyclic simple type %q", value)
	}
	visiting[ref.Local] = true
	err = s.simpleType(typeNode, visiting)
	delete(visiting, ref.Local)
	return err
}

func (s *schema) simpleType(n *node, visiting map[string]bool) error {
	if err := n.validate("simpleType", "name"); err != nil {
		return err
	}
	if len(n.children) != 1 {
		return fmt.Errorf("simple type requires one restriction")
	}
	r := n.children[0]
	if err := r.validate("restriction", "base"); err != nil {
		return err
	}
	if err := s.typeReference(r, r.attrs["base"], visiting); err != nil {
		return err
	}
	for _, facet := range r.children {
		switch facet.name.Local {
		case "enumeration", "minInclusive", "maxInclusive":
			if err := facet.validate(facet.name.Local, "value"); err != nil {
				return err
			}
			if len(facet.children) != 0 {
				return fmt.Errorf("unsupported facet children")
			}
		default:
			return fmt.Errorf("unsupported simple type facet %v", facet.name)
		}
	}
	return nil
}
