// Command oidcgen generates shared OIDC trust controls from a pinned AWS capture.
// It performs no network requests; source refresh is a separate explicit action.
package main

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strconv"
	"strings"
	"time"
)

type snapshot struct {
	Source    string     `json:"source"`
	Captured  string     `json:"captured_at"`
	SHA256    string     `json:"source_sha256"`
	Providers []provider `json:"providers"`
}

type provider struct {
	Provider string `json:"provider"`
	Issuer   string `json:"issuer"`
	Claim    string `json:"claim"`
}

func main() {
	source := flag.String("source", "iam/policy/testdata/oidc_trust_controls_source.json", "pinned source snapshot")
	output := flag.String("out", "iam/policy/trust_oidc_controls_data.go", "generated Go file")
	check := flag.Bool("check", false, "check drift without writing files")
	flag.Parse()
	if err := run(*source, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(sourcePath, outputPath string, check bool) error {
	raw, err := os.ReadFile(sourcePath)
	if err != nil {
		return err
	}
	var source snapshot
	if err := json.Unmarshal(raw, &source); err != nil {
		return err
	}
	generated, err := render(source)
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("OIDC trust controls are stale; run make generate-oidc")
		}
		return nil
	}
	return os.WriteFile(outputPath, generated, 0o644)
}

func render(source snapshot) ([]byte, error) {
	if source.Source != "https://docs.aws.amazon.com/IAM/latest/UserGuide/id_roles_providers_oidc_secure-by-default.html" {
		return nil, fmt.Errorf("unexpected shared-provider source URL")
	}
	if _, err := time.Parse(time.DateOnly, source.Captured); err != nil {
		return nil, fmt.Errorf("invalid source capture date: %w", err)
	}
	if digest, err := hex.DecodeString(source.SHA256); err != nil || len(digest) != 32 {
		return nil, fmt.Errorf("source must have a SHA-256 digest")
	}
	if len(source.Providers) == 0 {
		return nil, fmt.Errorf("source has no shared-provider controls")
	}
	providers := slices.Clone(source.Providers)
	slices.SortFunc(providers, func(a, b provider) int { return strings.Compare(a.Issuer, b.Issuer) })
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by cmd/oidcgen; DO NOT EDIT.\n// Source: %s\n// Captured: %s; source SHA256: %s\n\npackage policy\n\nvar sharedOIDCTrustClaims = map[string]string{\n", source.Source, source.Captured, source.SHA256)
	previous := ""
	for _, provider := range providers {
		if provider.Issuer == "" || provider.Issuer == previous || provider.Claim == "" || provider.Provider == "" {
			return nil, fmt.Errorf("provider rows require a name, unique issuer and condition key")
		}
		previous = provider.Issuer
		fmt.Fprintf(&out, "\t%s: %s,\n", strconv.Quote(provider.Issuer), strconv.Quote(provider.Claim))
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}
