// Command cloudtrailgen generates CloudTrail's documented data resource types.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"html"
	"io"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"time"
)

var sourceURLs = []string{
	"https://docs.aws.amazon.com/awscloudtrail/latest/userguide/logging-data-events-with-cloudtrail.html",
	"https://docs.aws.amazon.com/eventbridge/latest/userguide/logging-using-cloudtrail.html",
}

const outputPath = "internal/services/cloudtrail/resource_types_generated.go"

func main() {
	var sources []string
	flag.Func("source", "official data-event documentation URL or captured HTML path; repeat for each source (defaults to CloudTrail and EventBridge documentation)", func(value string) error {
		sources = append(sources, value)
		return nil
	})
	check := flag.Bool("check", false, "check generated output without writing")
	flag.Parse()
	if len(sources) == 0 {
		sources = sourceURLs
	}
	if err := run(sources, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func readSource(source string) ([]byte, error) {
	if !strings.HasPrefix(source, "https://") && !strings.HasPrefix(source, "http://") {
		return os.ReadFile(source)
	}
	client := http.Client{Timeout: 30 * time.Second}
	response, err := client.Get(source)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("documentation returned %s", response.Status)
	}
	return io.ReadAll(response.Body)
}

func run(sources []string, check bool) error {
	var types []string
	for _, source := range sources {
		data, err := readSource(source)
		if err != nil {
			return fmt.Errorf("%s: %w", source, err)
		}
		values, err := resourceTypes(data)
		if err != nil {
			return fmt.Errorf("%s: %w", source, err)
		}
		types = append(types, values...)
	}
	slices.Sort(types)
	types = slices.Compact(types)
	var output bytes.Buffer
	output.WriteString("// Code generated by cmd/cloudtrailgen; DO NOT EDIT.\n")
	for _, source := range sources {
		fmt.Fprintf(&output, "// Source: %s\n", source)
	}
	output.WriteString("\npackage cloudtrail\n\nfunc validResourceType(value string) bool {\n\tswitch value {\n")
	for _, resourceType := range types {
		fmt.Fprintf(&output, "\tcase %q:\n\t\treturn true\n", resourceType)
	}
	output.WriteString("\t}\n\treturn false\n}\n")
	generated, err := format.Source(output.Bytes())
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("CloudTrail resource types are stale; run go run ./cmd/cloudtrailgen")
		}
		fmt.Printf("CloudTrail resource types are current (%d documented types)\n", len(types))
		return nil
	}
	if err := os.WriteFile(outputPath, generated, 0o644); err != nil {
		return err
	}
	fmt.Printf("Generated %s (%d documented types)\n", outputPath, len(types))
	return nil
}

func resourceTypes(data []byte) ([]string, error) {
	// Parse only data-table rows and their resource-type column, never code
	// examples or resource names mentioned in a description. HTML wrappers in
	// cells are presentation; the documented column value is the vocabulary.
	tables := regexp.MustCompile(`(?is)<table\b[^>]*>(.*?)</table>`)
	rows := regexp.MustCompile(`(?is)<tr\b[^>]*>(.*?)</tr>`)
	headers := regexp.MustCompile(`(?is)<th\b[^>]*>(.*?)</th>`)
	cells := regexp.MustCompile(`(?is)<td\b[^>]*>(.*?)</td>`)
	tags := regexp.MustCompile(`<[^>]*>`)
	validType := regexp.MustCompile(`^AWS::[A-Za-z0-9]+::[A-Za-z0-9]+$`)
	text := func(cell []byte) string {
		return strings.TrimSpace(html.UnescapeString(string(tags.ReplaceAll(cell, nil))))
	}
	var types []string
	matchedTables := 0
	for _, table := range tables.FindAllSubmatch(data, -1) {
		columns := headers.FindAllSubmatch(table[1], -1)
		column := -1
		for i, header := range columns {
			if strings.Join(strings.Fields(text(header[1])), " ") == "resources.type value" {
				column = i
			}
		}
		if column < 0 {
			continue
		}
		matchedTables++
		for _, row := range rows.FindAllSubmatch(table[1], -1) {
			values := cells.FindAllSubmatch(row[1], -1)
			if len(values) == 0 {
				continue
			}
			if len(values) != len(columns) {
				return nil, fmt.Errorf("unexpected CloudTrail data resource row width: %d", len(values))
			}
			value := text(values[column][1])
			if !validType.MatchString(value) {
				return nil, fmt.Errorf("invalid documented CloudTrail data resource type %q", value)
			}
			types = append(types, value)
		}
	}
	if matchedTables != 1 || len(types) == 0 {
		return nil, fmt.Errorf("expected one nonempty CloudTrail data resource table, found %d", matchedTables)
	}
	slices.Sort(types)
	return slices.Compact(types), nil
}
