// Command terraformapisgen maps provider source evidence to stackd registrations.
// It is a static prioritization report, never a Terraform conformance assertion.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const pinnedRevision = "c9b83d813022cdd05fc955480b07e269c6e18023"
const pinnedVersion = "6.68.0"
const sdkPrefix = "github.com/aws/aws-sdk-go-v2/service/"

type options struct {
	Provider, Inventory, Out, Revision, Version string
	Check                                       bool
}

type callsite struct {
	Path       string `json:"path"`
	Line       int    `json:"line"`
	Function   string `json:"function,omitempty"`
	Expression string `json:"expression"`
	Evidence   string `json:"evidence"`
}

type requirement struct {
	SDKService    string     `json:"sdk_service"`
	StackdService string     `json:"stackd_service,omitempty"`
	Operation     string     `json:"operation"`
	Status        string     `json:"status"`
	Callsites     []callsite `json:"callsites"`
}

type unresolved struct {
	Callsite   callsite `json:"callsite"`
	Reason     string   `json:"reason"`
	Candidates []string `json:"candidates"`
}

type totals struct {
	Services      int `json:"provider_services"`
	Files         int `json:"production_files"`
	Requirements  int `json:"service_operation_requirements"`
	UniqueAPIs    int `json:"unique_sdk_service_operations"`
	Callsites     int `json:"resolved_callsites"`
	Paginators    int `json:"paginator_callsites"`
	Partial       int `json:"registered_partial"`
	Unimplemented int `json:"unimplemented"`
	Outside       int `json:"outside_selected_service_scope"`
	Unknown       int `json:"unresolved_or_ambiguous_requirements"`
	Unresolved    int `json:"unresolved_callsites"`
}

type service struct {
	Name          string        `json:"provider_service"`
	Files         int           `json:"production_files"`
	ExcludedFiles int           `json:"excluded_test_or_sweeper_files"`
	Requirements  []requirement `json:"required_apis"`
	Unresolved    []unresolved  `json:"unresolved"`
}

type priority struct {
	Service       string `json:"provider_service"`
	Unimplemented int    `json:"unimplemented"`
	Unknown       int    `json:"unresolved_or_ambiguous"`
	Outside       int    `json:"outside_selected_service_scope"`
	Callsites     int    `json:"unimplemented_callsites"`
}

type gap struct {
	ProviderService string   `json:"provider_service"`
	SDKService      string   `json:"sdk_service"`
	Operation       string   `json:"operation"`
	Callsites       int      `json:"callsites"`
	Example         callsite `json:"example"`
}

type source struct {
	Repository string `json:"repository"`
	Revision   string `json:"revision"`
	Version    string `json:"version"`
	Path       string `json:"path"`
	SHA256     string `json:"production_source_sha256"`
}

type report struct {
	SchemaVersion           int              `json:"schema_version"`
	Source                  source           `json:"provider"`
	Inventory               map[string]any   `json:"stackd_inventory"`
	Interpretation          string           `json:"interpretation"`
	AnalysisLimits          []string         `json:"analysis_limits"`
	KnownLifecycleContracts []map[string]any `json:"known_lifecycle_contracts"`
	Totals                  totals           `json:"totals"`
	Priorities              []priority       `json:"priority_counts"`
	TopGaps                 []gap            `json:"top_selected_scope_api_gaps"`
	Services                []service        `json:"services"`
}

type retained struct {
	Source   map[string]any `json:"source"`
	Services []struct {
		ID         string                          `json:"id"`
		Operations []struct{ Name, Status string } `json:"operations"`
	} `json:"services"`
	Additional []struct {
		Service    string                          `json:"service"`
		Operations []struct{ Name, Status string } `json:"operations"`
	} `json:"additional_registered"`
}

type analyzer struct {
	fset       *token.FileSet
	file       *ast.File
	path       string
	imports    map[string]string
	operations map[string]map[string]bool
}

func main() {
	var o options
	flag.StringVar(&o.Provider, "provider", "clones/terraform-provider-aws", "local provider checkout")
	flag.StringVar(&o.Inventory, "inventory", "docs/services.json", "retained modeled and registered stackd inventory")
	flag.StringVar(&o.Out, "out", "docs/terraform-provider-apis.json", "generated source-backed report")
	flag.StringVar(&o.Revision, "revision", pinnedRevision, "required provider commit")
	flag.StringVar(&o.Version, "version", pinnedVersion, "required provider version")
	flag.BoolVar(&o.Check, "check", false, "compare deterministic generated bytes without writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "terraformapisgen: unexpected positional arguments")
		os.Exit(2)
	}
	if err := run(o); err != nil {
		fmt.Fprintln(os.Stderr, "terraformapisgen:", err)
		os.Exit(1)
	}
}

func run(o options) error {
	r, err := generate(o)
	if err != nil {
		return err
	}
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	current, err := os.ReadFile(o.Out)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if bytes.Equal(current, data) {
		return nil
	}
	if o.Check {
		return fmt.Errorf("generated inventory differs: %s; regenerate with go run ./cmd/terraformapisgen -provider %q -inventory %q -out %q -revision %q -version %q", o.Out, o.Provider, o.Inventory, o.Out, o.Revision, o.Version)
	}
	if err := os.MkdirAll(filepath.Dir(o.Out), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(o.Out), ".terraformapisgen-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(0o644); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), o.Out)
}

func generate(o options) (report, error) {
	r := report{SchemaVersion: 1, Services: []service{}, Priorities: []priority{}, TopGaps: []gap{}}
	revision, err := git(o.Provider, "rev-parse", "HEAD")
	if err != nil {
		return r, err
	}
	versionBytes, err := os.ReadFile(filepath.Join(o.Provider, "version", "VERSION"))
	if err != nil {
		return r, err
	}
	version := strings.TrimSpace(string(versionBytes))
	if revision != o.Revision || version != o.Version {
		return r, fmt.Errorf("provider must be version %s at %s; found %s at %s", o.Version, o.Revision, version, revision)
	}
	dirty, err := git(o.Provider, "status", "--porcelain", "--untracked-files=all", "--", "internal/service", "version/VERSION")
	if err != nil {
		return r, err
	}
	if dirty != "" {
		return r, errors.New("provider service/version source has local changes; source links require a clean pinned checkout")
	}
	inventoryBytes, err := os.ReadFile(o.Inventory)
	if err != nil {
		return r, err
	}
	var inventory retained
	if err := json.Unmarshal(inventoryBytes, &inventory); err != nil {
		return r, err
	}
	statuses := map[string]map[string]string{}
	operations := map[string]map[string]bool{}
	for _, s := range inventory.Services {
		key := sdkID(s.ID)
		if _, exists := statuses[key]; exists {
			return r, fmt.Errorf("ambiguous SDK service mapping for %s", s.ID)
		}
		statuses[key] = map[string]string{}
		operations[key] = map[string]bool{}
		for _, op := range s.Operations {
			statuses[key][op.Name] = op.Status
			operations[key][op.Name] = true
		}
	}
	for _, s := range inventory.Additional {
		key := sdkID(s.Service)
		if statuses[key] == nil {
			statuses[key] = map[string]string{}
			operations[key] = map[string]bool{}
		}
		for _, op := range s.Operations {
			statuses[key][op.Name] = op.Status
			operations[key][op.Name] = true
		}
	}
	digest := sha256.Sum256(inventoryBytes)
	r.Inventory = map[string]any{"path": filepath.ToSlash(o.Inventory), "sha256": hex.EncodeToString(digest[:]), "source": inventory.Source}
	r.Source = source{Repository: "https://github.com/hashicorp/terraform-provider-aws", Revision: revision, Version: version, Path: "internal/service"}
	r.Interpretation = "Static, source-backed required-API prioritization map, not semantic completeness, a resource support promise, or an IAM policy. Registered-partial means a retained default-stack registration only. Counts are provider-directory/SDK-service/operation tuples; unique SDK API counts deduplicate across directories. Unresolved candidates are not counted as required APIs."
	r.AnalysisLimits = []string{
		"Parses every .go file recursively under every internal/service directory, excluding *_test.go, sweep.go, sweep_*.go, *_sweep.go, testdata and test-fixtures. Generated production helpers are included. All remaining build variants are analyzed, not just one host's selected build tags.",
		"Uses Go AST import identity, lexical object declarations, explicit SDK Client/Input types, AWSClient getter identities and SDK New<Operation>Paginator constructors. No provider compilation, full Go type checking, network calls or resource lifecycle execution is performed.",
		"SDK operation calls resolve from a matching SDK <Operation>Input argument or an inferred SDK Client receiver. Getter inference requires a conns.AWSClient receiver and a matching imported SDK service. Imported aliases are honored; field receivers, aliases across files, custom generic wrappers, reflection and dynamic method dispatch may remain unresolved.",
		"Potential SDK method references, indirect calls with a matching Input and operation-shaped calls on unresolved conn/client receivers are recorded with candidates, not silently treated as complete. Candidates use retained modeled operation names when possible; outside-scope candidates are inherently ambiguous.",
		"SDK constructors and method references inside internal/service are scanned, but transitive API calls implemented entirely outside internal/service (provider initialization, shared helpers, credential discovery, tagging frameworks) are outside the source boundary. No absence-of-call or complete-resource-coverage assertion is valid.",
		"Priority order ranks selected-scope missing registrations by unique API count then source callsite count; top gaps rank static call frequency, not runtime frequency, Terraform popularity or dependency/reachability. Required field values, request branches, waiters, pagination behavior, IAM and native-runtime enforcement require separate evidence.",
		"Retained docs/services.json may use an older Smithy model than the provider SDK. A call for a selected service absent from that model is unresolved-or-ambiguous, never silently labeled unimplemented. Services not selected are outside-selected-service-scope, not implementation commitments.",
	}
	r.KnownLifecycleContracts = lifecycleContracts(revision)
	entries, err := os.ReadDir(filepath.Join(o.Provider, "internal", "service"))
	if err != nil {
		return r, err
	}
	hash := sha256.New()
	unique := map[string]bool{}
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		s := service{Name: entry.Name(), Requirements: []requirement{}, Unresolved: []unresolved{}}
		byAPI := map[string]*requirement{}
		root := filepath.Join(o.Provider, "internal", "service", entry.Name())
		err := filepath.WalkDir(root, func(path string, d os.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if d.IsDir() {
				if d.Name() == "testdata" || d.Name() == "test-fixtures" {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(d.Name(), ".go") {
				return nil
			}
			if excluded(d.Name()) {
				s.ExcludedFiles++
				return nil
			}
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			rel, err := filepath.Rel(o.Provider, path)
			if err != nil {
				return err
			}
			rel = filepath.ToSlash(rel)
			fmt.Fprintf(hash, "%s\x00%d\x00", rel, len(data))
			_, _ = hash.Write(data)
			fset := token.NewFileSet()
			file, err := parser.ParseFile(fset, rel, data, 0)
			if err != nil {
				return err
			}
			s.Files++
			a := analyzer{fset: fset, file: file, path: rel, imports: sdkImports(file), operations: operations}
			a.scan(func(sdk, op string, site callsite) {
				key := sdk + "/" + op
				req := byAPI[key]
				if req == nil {
					status, stackd := classify(sdk, op, inventory, statuses)
					req = &requirement{SDKService: sdk, StackdService: stackd, Operation: op, Status: status, Callsites: []callsite{}}
					byAPI[key] = req
				}
				req.Callsites = append(req.Callsites, site)
			}, func(u unresolved) { s.Unresolved = append(s.Unresolved, u) })
			return nil
		})
		if err != nil {
			return r, fmt.Errorf("analyze %s: %w", s.Name, err)
		}
		keys := make([]string, 0, len(byAPI))
		for key := range byAPI {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		p := priority{Service: s.Name}
		for _, key := range keys {
			req := *byAPI[key]
			sort.Slice(req.Callsites, func(i, j int) bool { return siteLess(req.Callsites[i], req.Callsites[j]) })
			s.Requirements = append(s.Requirements, req)
			unique[key] = true
			r.Totals.Requirements++
			r.Totals.Callsites += len(req.Callsites)
			for _, site := range req.Callsites {
				if site.Evidence == "sdk_paginator_constructor" {
					r.Totals.Paginators++
				}
			}
			switch req.Status {
			case "registered-partial":
				r.Totals.Partial++
			case "unimplemented":
				r.Totals.Unimplemented++
				p.Unimplemented++
				p.Callsites += len(req.Callsites)
				r.TopGaps = append(r.TopGaps, gap{ProviderService: s.Name, SDKService: req.SDKService, Operation: req.Operation, Callsites: len(req.Callsites), Example: req.Callsites[0]})
			case "outside-selected-service-scope":
				r.Totals.Outside++
				p.Outside++
			default:
				r.Totals.Unknown++
				p.Unknown++
			}
		}
		sort.Slice(s.Unresolved, func(i, j int) bool { return siteLess(s.Unresolved[i].Callsite, s.Unresolved[j].Callsite) })
		r.Totals.Files += s.Files
		r.Totals.Unresolved += len(s.Unresolved)
		r.Priorities = append(r.Priorities, p)
		r.Services = append(r.Services, s)
	}
	r.Source.SHA256 = hex.EncodeToString(hash.Sum(nil))
	r.Totals.Services = len(r.Services)
	r.Totals.UniqueAPIs = len(unique)
	sort.Slice(r.Priorities, func(i, j int) bool {
		a, b := r.Priorities[i], r.Priorities[j]
		if a.Unimplemented != b.Unimplemented {
			return a.Unimplemented > b.Unimplemented
		}
		if a.Callsites != b.Callsites {
			return a.Callsites > b.Callsites
		}
		return a.Service < b.Service
	})
	sort.Slice(r.TopGaps, func(i, j int) bool {
		a, b := r.TopGaps[i], r.TopGaps[j]
		if a.Callsites != b.Callsites {
			return a.Callsites > b.Callsites
		}
		return a.ProviderService+"/"+a.SDKService+"/"+a.Operation < b.ProviderService+"/"+b.SDKService+"/"+b.Operation
	})
	if len(r.TopGaps) > 30 {
		r.TopGaps = r.TopGaps[:30]
	}
	return r, nil
}

func git(path string, args ...string) (string, error) {
	cmd := exec.Command("git", append([]string{"-C", path}, args...)...)
	data, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("provider metadata: %w: %s", err, data)
	}
	return strings.TrimSpace(string(data)), nil
}

func excluded(name string) bool {
	return strings.HasSuffix(name, "_test.go") || name == "sweep.go" || strings.HasPrefix(name, "sweep_") || strings.HasSuffix(name, "_sweep.go")
}

func sdkID(id string) string {
	switch id {
	case "elbv2":
		return "elasticloadbalancingv2"
	case "elb":
		return "elasticloadbalancing"
	case "logs":
		return "cloudwatchlogs"
	case "ce":
		return "costexplorer"
	case "cognitoidp":
		return "cognitoidentityprovider"
	case "es":
		return "elasticsearchservice"
	case "iot-data":
		return "iotdataplane"
	case "serverlessrepo":
		return "serverlessapplicationrepository"
	case "stepfunctions":
		return "sfn"
	default:
		return strings.ReplaceAll(id, "-", "")
	}
}

func classify(sdk, op string, inventory retained, statuses map[string]map[string]string) (string, string) {
	for _, s := range inventory.Services {
		if sdkID(s.ID) != sdk {
			continue
		}
		switch statuses[sdk][op] {
		case "partial":
			return "registered-partial", s.ID
		case "unimplemented":
			return "unimplemented", s.ID
		default:
			return "unresolved-or-ambiguous", s.ID
		}
	}
	// Additional registrations do not expand the explicitly selected service scope.
	return "outside-selected-service-scope", ""
}

func sdkImports(file *ast.File) map[string]string {
	imports := map[string]string{}
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil || !strings.HasPrefix(path, sdkPrefix) {
			continue
		}
		sdk := strings.TrimPrefix(path, sdkPrefix)
		if strings.Contains(sdk, "/") {
			continue
		}
		alias := sdk
		if spec.Name != nil {
			alias = spec.Name.Name
		}
		if alias != "_" && alias != "." {
			imports[alias] = sdk
		}
	}
	return imports
}

func (a analyzer) scan(resolve func(string, string, callsite), record func(unresolved)) {
	for _, decl := range a.file.Decls {
		var node ast.Node = decl
		function := "<package>"
		if fn, ok := decl.(*ast.FuncDecl); ok {
			if fn.Body == nil {
				continue
			}
			node = fn.Body
			function = fn.Name.Name
		}
		called := map[*ast.SelectorExpr]bool{}
		ast.Inspect(node, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				if ident, ok := call.Fun.(*ast.Ident); ok && ident.Obj != nil && len(call.Args) > 1 && !declaredFunction(ident) {
					sdk, typ := a.infer(call.Args[1], 0)
					if sdk != "" && strings.HasSuffix(typ, "Input") {
						op := strings.TrimSuffix(typ, "Input")
						record(unresolved{Callsite: a.site(call.Pos(), function, ident.Name, "indirect_input_typed_call"), Reason: "Call target is a local function value; SDK Input alone does not prove dynamic dispatch.", Candidates: []string{sdk + "/" + op}})
					}
				}
				return true
			}
			called[sel] = true
			name := sel.Sel.Name
			if pkg, ok := sel.X.(*ast.Ident); ok {
				if sdk := a.imports[pkg.Name]; sdk != "" {
					if strings.HasPrefix(name, "New") && strings.HasSuffix(name, "Paginator") {
						op := strings.TrimSuffix(strings.TrimPrefix(name, "New"), "Paginator")
						if op != "" {
							resolve(sdk, op, a.site(call.Pos(), function, pkg.Name+"."+name, "sdk_paginator_constructor"))
						}
					}
					return true
				}
			}
			if len(call.Args) > 1 {
				sdk, typ := a.infer(call.Args[1], 0)
				if sdk != "" && typ == name+"Input" {
					resolve(sdk, name, a.site(call.Pos(), function, receiverName(sel.X)+"."+name, "sdk_input_argument"))
					return true
				}
			}
			sdk, typ := a.infer(sel.X, 0)
			if sdk != "" && typ == "Client" && name != "Options" {
				resolve(sdk, name, a.site(call.Pos(), function, receiverName(sel.X)+"."+name, "sdk_client_receiver"))
				return true
			}
			if operationName(name) && suspiciousReceiver(sel.X) {
				candidates := a.candidates(name)
				record(unresolved{Callsite: a.site(call.Pos(), function, receiverName(sel.X)+"."+name, "unresolved_receiver"), Reason: "Operation-shaped method on conn/client receiver without provable SDK identity.", Candidates: candidates})
			}
			return true
		})
		ast.Inspect(node, func(n ast.Node) bool {
			sel, ok := n.(*ast.SelectorExpr)
			if !ok || called[sel] || sel.Sel.Name == "Options" {
				return true
			}
			sdk, typ := a.infer(sel.X, 0)
			if sdk != "" && typ == "Client" {
				record(unresolved{Callsite: a.site(sel.Pos(), function, receiverName(sel.X)+"."+sel.Sel.Name, "sdk_method_reference"), Reason: "SDK method value is referenced but invocation/reachability is not resolved.", Candidates: []string{sdk + "/" + sel.Sel.Name}})
			}
			return true
		})
	}
}

// infer follows lexical parser object bindings, not a file-wide name table: a
// shadowed conn/input cannot accidentally inherit another function's SDK type.
func (a analyzer) infer(expr ast.Expr, depth int) (string, string) {
	if depth > 12 || expr == nil {
		return "", ""
	}
	switch e := expr.(type) {
	case *ast.ParenExpr:
		return a.infer(e.X, depth+1)
	case *ast.StarExpr:
		return a.infer(e.X, depth+1)
	case *ast.UnaryExpr:
		return a.infer(e.X, depth+1)
	case *ast.CompositeLit:
		return a.infer(e.Type, depth+1)
	case *ast.SelectorExpr:
		if id, ok := e.X.(*ast.Ident); ok {
			return a.imports[id.Name], e.Sel.Name
		}
	case *ast.CallExpr:
		if sel, ok := e.Fun.(*ast.SelectorExpr); ok && strings.HasSuffix(sel.Sel.Name, "Client") && a.providerClient(sel.X, 0) {
			if id, ok := sel.X.(*ast.Ident); ok && a.imports[id.Name] != "" {
				return "", ""
			}
			getter := strings.ToLower(strings.TrimSuffix(sel.Sel.Name, "Client"))
			for _, sdk := range a.imports {
				if sdk == getter {
					return sdk, "Client"
				}
			}
		}
	case *ast.Ident:
		if e.Obj == nil {
			return "", ""
		}
		switch decl := e.Obj.Decl.(type) {
		case *ast.Field:
			return a.infer(decl.Type, depth+1)
		case *ast.ValueSpec:
			if decl.Type != nil {
				return a.infer(decl.Type, depth+1)
			}
			for i, id := range decl.Names {
				if id.Name == e.Name && i < len(decl.Values) {
					return a.infer(decl.Values[i], depth+1)
				}
			}
		case *ast.AssignStmt:
			for i, lhs := range decl.Lhs {
				if id, ok := lhs.(*ast.Ident); ok && id.Obj == e.Obj && i < len(decl.Rhs) {
					return a.infer(decl.Rhs[i], depth+1)
				}
			}
		}
	}
	return "", ""
}

func declaredFunction(id *ast.Ident) bool {
	_, ok := id.Obj.Decl.(*ast.FuncDecl)
	return ok
}

// A factory name is insufficient by itself: require the receiver to originate
// in the provider's conns.AWSClient type before treating it as an SDK client.
func (a analyzer) providerClient(expr ast.Expr, depth int) bool {
	if expr == nil || depth > 12 {
		return false
	}
	switch e := expr.(type) {
	case *ast.ParenExpr:
		return a.providerClient(e.X, depth+1)
	case *ast.StarExpr:
		return a.providerClient(e.X, depth+1)
	case *ast.TypeAssertExpr:
		return a.providerClient(e.Type, depth+1)
	case *ast.SelectorExpr:
		if e.Sel.Name != "AWSClient" {
			return false
		}
		pkg, ok := e.X.(*ast.Ident)
		if !ok {
			return false
		}
		for _, spec := range a.file.Imports {
			path, err := strconv.Unquote(spec.Path.Value)
			if err != nil || path != "github.com/hashicorp/terraform-provider-aws/internal/conns" {
				continue
			}
			alias := "conns"
			if spec.Name != nil {
				alias = spec.Name.Name
			}
			return pkg.Name == alias
		}
	case *ast.Ident:
		if e.Obj == nil {
			return false
		}
		switch decl := e.Obj.Decl.(type) {
		case *ast.Field:
			return a.providerClient(decl.Type, depth+1)
		case *ast.ValueSpec:
			if decl.Type != nil {
				return a.providerClient(decl.Type, depth+1)
			}
			for i, id := range decl.Names {
				if id.Name == e.Name && i < len(decl.Values) {
					return a.providerClient(decl.Values[i], depth+1)
				}
			}
		case *ast.AssignStmt:
			for i, lhs := range decl.Lhs {
				if id, ok := lhs.(*ast.Ident); ok && id.Obj == e.Obj && i < len(decl.Rhs) {
					return a.providerClient(decl.Rhs[i], depth+1)
				}
			}
		}
	}
	return false
}

func (a analyzer) candidates(op string) []string {
	candidates := []string{}
	seen := map[string]bool{}
	for _, sdk := range a.imports {
		if seen[sdk] {
			continue
		}
		seen[sdk] = true
		if a.operations[sdk] == nil || a.operations[sdk][op] {
			candidates = append(candidates, sdk+"/"+op)
		}
	}
	sort.Strings(candidates)
	return candidates
}

func (a analyzer) site(pos token.Pos, fn, expression, evidence string) callsite {
	return callsite{Path: a.path, Line: a.fset.Position(pos).Line, Function: fn, Expression: expression, Evidence: evidence}
}

func receiverName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		return receiverName(e.X) + "." + e.Sel.Name
	case *ast.CallExpr:
		return receiverName(e.Fun) + "()"
	case *ast.ParenExpr:
		return receiverName(e.X)
	default:
		return "<expression>"
	}
}

func suspiciousReceiver(expr ast.Expr) bool {
	name := strings.ToLower(receiverName(expr))
	return strings.Contains(name, "conn") || strings.Contains(name, "client")
}

func operationName(name string) bool {
	// This is only an unresolved-candidate filter, not a regex-based API inventory.
	for _, prefix := range []string{"Accept", "Activate", "Add", "Allocate", "Apply", "Associate", "Attach", "Authorize", "Batch", "Cancel", "Change", "Check", "Complete", "Copy", "Create", "Deactivate", "Delete", "Deregister", "Describe", "Detach", "Disable", "Disassociate", "Enable", "Execute", "Export", "Get", "Import", "Invoke", "List", "Modify", "Monitor", "Move", "Put", "Reboot", "Register", "Reject", "Release", "Remove", "Replace", "Reset", "Restore", "Resume", "Revoke", "Run", "Send", "Set", "Start", "Stop", "Subscribe", "Tag", "Terminate", "Untag", "Update", "Upload", "Validate", "Wait"} {
		if strings.HasPrefix(name, prefix) && len(name) > len(prefix) {
			return true
		}
	}
	return false
}

func siteLess(a, b callsite) bool {
	if a.Path != b.Path {
		return a.Path < b.Path
	}
	if a.Line != b.Line {
		return a.Line < b.Line
	}
	return a.Expression < b.Expression
}

