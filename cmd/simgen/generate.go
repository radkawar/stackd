package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

type capture struct {
	CaptureComplete bool          `json:"capture_complete"`
	Actions         []observation `json:"actions"`
}

type observation struct {
	Action                  string         `json:"action"`
	Code                    string         `json:"code"`
	EvalResourceName        string         `json:"eval_resource_name"`
	EvalResourceNamePresent *bool          `json:"eval_resource_name_present"`
	ResourceAware           *bool          `json:"resource_aware"`
	DefaultResult           *defaultResult `json:"default_result"`
}

type defaultResult struct {
	ResourceName string `json:"eval_resource_name"`
	Present      bool   `json:"eval_resource_name_present"`
}

func generate(source, handling []byte) ([]byte, error) {
	var data capture
	if err := json.Unmarshal(source, &data); err != nil {
		return nil, err
	}
	if !data.CaptureComplete || len(data.Actions) == 0 {
		return nil, fmt.Errorf("simulation capture is incomplete")
	}
	slices.SortFunc(data.Actions, func(a, b observation) int { return strings.Compare(a.Action, b.Action) })
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./cmd/simgen; DO NOT EDIT.\n")
	out.WriteString("// Source: testdata/aws/iam/simulation_catalog.json (AWS SimulateCustomPolicy).\n\n")
	out.WriteString("package simcatalog\n\nvar generatedActions = map[string]Action{\n")
	for index, action := range data.Actions {
		if action.Code != "Success" || action.Action == "" || action.EvalResourceNamePresent == nil || action.ResourceAware == nil {
			return nil, fmt.Errorf("action %q has no successful simulation observation", action.Action)
		}
		if index > 0 && data.Actions[index-1].Action == action.Action {
			return nil, fmt.Errorf("duplicate simulation action %q", action.Action)
		}
		if action.DefaultResult == nil || !action.DefaultResult.Present || action.DefaultResult.ResourceName == "" {
			return nil, fmt.Errorf("action %q has no default resource name observation", action.Action)
		}
		// The capture normalizes the authenticated account to 123456789012.
		// AWS's own literal ${Account}/${Partition} placeholders stay literal.
		defaultName := strings.ReplaceAll(action.DefaultResult.ResourceName, ":123456789012:", ":${AuthenticatedAccount}:")
		fmt.Fprintf(&out, "%q: {AggregateTemplate: %q, DefaultResourceTemplate: %q, HasAggregateTemplate: %t, ResourceAware: %t},\n", action.Action, action.EvalResourceName, defaultName, *action.EvalResourceNamePresent, *action.ResourceAware)
	}
	out.WriteString("}\n")
	scenarios, err := resourceHandlingMetadata(handling)
	if err != nil {
		return nil, err
	}
	out.Write(scenarios)
	return format.Source(out.Bytes())
}
