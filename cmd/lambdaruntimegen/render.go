package main

import (
	"bytes"
	"fmt"
	"go/token"
	"strings"
	"unicode"
	"unicode/utf8"
)

func generatedHeader(pkg string) string {
	return "// Code generated by go run ./cmd/lambdaruntimegen; DO NOT EDIT.\n\npackage " + pkg + "\n\n"
}

func exported(name string) (string, error) {
	r, size := utf8.DecodeRuneInString(name)
	name = string(unicode.ToUpper(r)) + name[size:]
	if !token.IsIdentifier(name) || !unicode.IsUpper([]rune(name)[0]) {
		return "", fmt.Errorf("schema name %q is not a Go exported identifier", name)
	}
	return name, nil
}

func declarationName(doc *document, name string) (string, error) {
	return exported(doc.Source.Prefix + name)
}

func renderTypes(pkg string, docs []*document) ([]byte, error) {
	var body bytes.Buffer
	seen := map[string]bool{}
	for _, doc := range docs {
		if doc.Source.Role == "transport" {
			continue
		}
		if doc.Source.Role != "bindings" && doc.Source.Role != "request" && doc.Source.Role != "events" {
			return nil, fmt.Errorf("unsupported source role %q", doc.Source.Role)
		}
		fmt.Fprintf(&body, "// Source: %s (%s).\n", doc.Source.URL, doc.Source.Revision)
		for _, name := range sortedKeys(doc.Shapes) {
			goName, err := declarationName(doc, name)
			if err != nil {
				return nil, err
			}
			if seen[goName] {
				return nil, fmt.Errorf("duplicate generated declaration %s", goName)
			}
			seen[goName] = true
			kind, err := goType(doc, doc.Shapes[name], name)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", goName, err)
			}
			fmt.Fprintf(&body, "type %s %s\n\n", goName, kind)
		}
	}
	var result bytes.Buffer
	result.WriteString(generatedHeader(pkg))
	if strings.Contains(body.String(), "json.RawMessage") {
		result.WriteString("import \"encoding/json\"\n\n")
	}
	result.Write(body.Bytes())
	return result.Bytes(), nil
}

func goType(doc *document, s *shape, path string) (string, error) {
	switch s.Kind {
	case "ref":
		return declarationName(doc, s.Ref)
	case "string":
		return "string", nil
	case "integer":
		switch s.Format {
		case "uint", "uint64":
			return "uint64", nil
		case "uint16":
			return "uint16", nil
		case "uint32":
			return "uint32", nil
		case "int32":
			return "int32", nil
		default:
			return "int64", nil
		}
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "any":
		return "json.RawMessage", nil
	case "array":
		item, err := goType(doc, s.Items, path+"[]")
		if err != nil {
			return "", err
		}
		if s.Items.Nullable && s.Items.Kind != "any" && s.Items.Kind != "array" {
			item = "*" + item
		}
		return "[]" + item, nil
	case "object":
		var body strings.Builder
		body.WriteString("struct {\n")
		fields := map[string]bool{}
		for _, name := range sortedKeys(s.Properties) {
			f := s.Properties[name]
			fieldName, err := exported(name)
			if err != nil {
				return "", err
			}
			if fields[fieldName] {
				return "", fmt.Errorf("%s: colliding field %s", path, fieldName)
			}
			fields[fieldName] = true
			fieldType, err := goType(doc, f.Shape, path+"."+name)
			if err != nil {
				return "", err
			}
			optional := !f.Required || f.Shape.Nullable
			// Pointers at the request boundary preserve missing/null values for
			// native validation. Destination alternatives are flattened rather
			// than pretending their branch-specific required fields are global.
			if doc.Source.Role == "request" && (path == "Destination" || path == "Subscription" && name == "destination") {
				optional = true
			}
			if optional && f.Shape.Kind != "array" && f.Shape.Kind != "any" {
				fieldType = "*" + fieldType
			}
			tag := name
			if optional {
				tag += ",omitempty"
			}
			fmt.Fprintf(&body, "%s %s `json:%q`\n", fieldName, fieldType, tag)
		}
		body.WriteString("}")
		return body.String(), nil
	default:
		return "", fmt.Errorf("%s: unsupported Go shape %s", path, s.Kind)
	}
}
