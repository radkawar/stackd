// Command sqlitegen derives fresh-database SQL from the authoritative migrations
// using the same SQLite engine as the running emulator.
package main

import (
	"bytes"
	"context"
	"database/sql"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"stackd/storage/sqlite/schema"

	_ "modernc.org/sqlite"
)

func main() {
	output := flag.String("out", "storage/sqlite/bootstrap_generated.go", "generated Go file")
	check := flag.Bool("check", false, "check drift without writing files")
	flag.Parse()
	if err := run(*output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(output string, check bool) error {
	ctx := context.Background()
	db, err := sql.Open("sqlite", "file::memory:?_pragma=foreign_keys(1)")
	if err != nil {
		return err
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	version, err := schema.Apply(ctx, tx, 0)
	if err != nil {
		return err
	}
	body, err := dump(ctx, tx)
	if err != nil {
		return err
	}
	body += fmt.Sprintf("PRAGMA user_version = %d;\n", version)
	generated, err := format.Source(fmt.Appendf(nil, "// Code generated by cmd/sqlitegen; DO NOT EDIT.\n// Source: storage/sqlite/schema/*.sql\n\npackage sqlite\n\nconst bootstrapVersion = %d\n\nconst bootstrapSchema = %s\n", version, strconv.Quote(body)))
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("SQLite bootstrap is stale; run make generate-sql")
		}
		return nil
	}
	return os.WriteFile(output, generated, 0o644)
}

type schemaObject struct{ kind, name, statement string }

func dump(ctx context.Context, tx *sql.Tx) (string, error) {
	rows, err := tx.QueryContext(ctx, `SELECT type, name, sql FROM sqlite_schema
		WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
		ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, name`)
	if err != nil {
		return "", err
	}
	var objects []schemaObject
	for rows.Next() {
		var object schemaObject
		if err := rows.Scan(&object.kind, &object.name, &object.statement); err != nil {
			rows.Close()
			return "", err
		}
		objects = append(objects, object)
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return "", err
	}
	if err := rows.Close(); err != nil {
		return "", err
	}
	var body strings.Builder
	for _, object := range objects {
		body.WriteString(object.statement)
		body.WriteString(";\n")
		if object.kind == "table" {
			if err := dumpRows(ctx, tx, object.name, &body); err != nil {
				return "", err
			}
		}
	}
	return body.String(), nil
}

func identifier(name string) string { return `"` + strings.ReplaceAll(name, `"`, `""`) + `"` }

func dumpRows(ctx context.Context, tx *sql.Tx, table string, body *strings.Builder) error {
	rows, err := tx.QueryContext(ctx, "SELECT name FROM pragma_table_info(?) ORDER BY cid", table)
	if err != nil {
		return err
	}
	var columns, quoted []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			rows.Close()
			return err
		}
		column := identifier(name)
		columns = append(columns, column)
		quoted = append(quoted, "quote("+column+")")
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return err
	}
	if err := rows.Close(); err != nil {
		return err
	}
	rows, err = tx.QueryContext(ctx, "SELECT "+strings.Join(quoted, ",")+" FROM "+identifier(table)+" ORDER BY "+strings.Join(columns, ","))
	if err != nil {
		return err
	}
	defer rows.Close()
	var values []string
	var destinations []any
	for rows.Next() {
		if values == nil {
			values = make([]string, len(columns))
			destinations = make([]any, len(columns))
			for i := range values {
				destinations[i] = &values[i]
			}
		}
		if err := rows.Scan(destinations...); err != nil {
			return err
		}
		fmt.Fprintf(body, "INSERT INTO %s (%s) VALUES (%s);\n", identifier(table), strings.Join(columns, ","), strings.Join(values, ","))
	}
	return rows.Err()
}
