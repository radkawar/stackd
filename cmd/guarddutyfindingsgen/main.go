// Command guarddutyfindingsgen records the upstream finding catalog and local
// declaration evidence. It does not assess AWS detection conformance.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const detectionGlob = "internal/services/guardduty/detection*.go"

// Finding preserves the upstream fields, including service order and nulls.
type Finding struct {
	Type         string   `json:"type"`
	ResourceType string   `json:"resource_type"`
	Source       string   `json:"source"`
	Severity     string   `json:"severity"`
	Services     []string `json:"services"`
}

type SourceCatalog struct {
	Findings []Finding `json:"findings"`
}

type Location struct {
	File   string `json:"file"`
	Line   int    `json:"line"`
	Column int    `json:"column"`
}

type Declaration struct {
	Status    string     `json:"status"`
	Locations []Location `json:"locations"`
}

type CatalogFinding struct {
	Finding
	LocalPredicate Declaration `json:"local_predicate"`
}

type UnknownFinding struct {
	Type           string      `json:"type"`
	LocalPredicate Declaration `json:"local_predicate"`
}

type Provenance struct {
	RepositoryURL           string `json:"repository_url"`
	Revision                string `json:"revision"`
	SourceFile              string `json:"source_file"`
	SourceSHA256            string `json:"source_sha256"`
	SourceDiffersFromCommit bool   `json:"source_differs_from_commit"`
}

type Evidence struct {
	Kind               string `json:"kind"`
	Scope              string `json:"scope"`
	Method             string `json:"method"`
	UnknownTypePattern string `json:"unknown_type_pattern"`
	Limitation         string `json:"limitation"`
}

type Catalog struct {
	SchemaVersion               int              `json:"schema_version"`
	Provenance                  Provenance       `json:"provenance"`
	Evidence                    Evidence         `json:"evidence"`
	Findings                    []CatalogFinding `json:"findings"`
	UnknownDeclaredFindingTypes []UnknownFinding `json:"unknown_declared_finding_types"`
}

// Unknown declarations are recognized by GuardDuty's ThreatPurpose:Resource/Finding
// spelling. Known catalog types are always matched exactly, independent of this pattern.
const unknownTypePattern = `^[A-Za-z][A-Za-z0-9]*:[A-Za-z][A-Za-z0-9]*/[A-Za-z0-9][A-Za-z0-9_.!:/-]*$`

func main() {
	source := flag.String("source", "clones/aws-guardduty-findings-directory/findings.json", "upstream findings JSON in its Git clone")
	out := flag.String("out", "docs/guardduty-findings.json", "generated catalog path")
	check := flag.Bool("check", false, "compare generated bytes without writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "unexpected positional arguments")
		os.Exit(1)
	}
	if err := run(*source, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(source, out string, check bool) error {
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	var input SourceCatalog
	if err := json.Unmarshal(data, &input); err != nil {
		return fmt.Errorf("decode catalog: %w", err)
	}
	if len(input.Findings) == 0 {
		return fmt.Errorf("source catalog has no findings")
	}
	known := make(map[string]bool, len(input.Findings))
	for _, finding := range input.Findings {
		if strings.TrimSpace(finding.Type) == "" {
			return fmt.Errorf("source catalog has an empty finding type")
		}
		if known[finding.Type] {
			return fmt.Errorf("duplicate finding type %q", finding.Type)
		}
		known[finding.Type] = true
	}
	provenance, err := sourceProvenance(source, data)
	if err != nil {
		return err
	}
	declarations, err := inspectDeclarations(known)
	if err != nil {
		return err
	}
	slices.SortFunc(input.Findings, func(a, b Finding) int { return strings.Compare(a.Type, b.Type) })
	catalog := Catalog{
		SchemaVersion: 1,
		Provenance:    provenance,
		Evidence: Evidence{
			Kind:               "declaration_only",
			Scope:              detectionGlob + " excluding *_test.go and Go-generated files",
			Method:             "Go AST string literals exactly equal to a catalog type; unknown types use the documented pattern. Comments are excluded.",
			UnknownTypePattern: unknownTypePattern,
			Limitation:         "local_predicate_declared records only a code literal location, not runtime reachability, detection behavior, completeness, or AWS conformance. no_local_predicate means no matching literal in the inspected files. Dynamically constructed type names are not inferred.",
		},
		Findings:                    make([]CatalogFinding, 0, len(input.Findings)),
		UnknownDeclaredFindingTypes: []UnknownFinding{},
	}
	for _, finding := range input.Findings {
		catalog.Findings = append(catalog.Findings, CatalogFinding{Finding: finding, LocalPredicate: declaration(declarations[finding.Type])})
	}
	for findingType, locations := range declarations {
		if !known[findingType] {
			catalog.UnknownDeclaredFindingTypes = append(catalog.UnknownDeclaredFindingTypes, UnknownFinding{Type: findingType, LocalPredicate: declaration(locations)})
		}
	}
	slices.SortFunc(catalog.UnknownDeclaredFindingTypes, func(a, b UnknownFinding) int { return strings.Compare(a.Type, b.Type) })
	generated, err := json.MarshalIndent(catalog, "", "  ")
	if err != nil {
		return err
	}
	generated = append(generated, '\n')
	if check {
		current, err := os.ReadFile(out)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("%s is stale; run go run ./cmd/guarddutyfindingsgen -source %q -out %q", out, source, out)
		}
		fmt.Printf("%s is current (%d catalog findings, %d unknown declarations)\n", out, len(catalog.Findings), len(catalog.UnknownDeclaredFindingTypes))
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(out, generated, 0o644); err != nil {
		return err
	}
	fmt.Printf("Generated %s (%d catalog findings, %d unknown declarations; declaration evidence only)\n", out, len(catalog.Findings), len(catalog.UnknownDeclaredFindingTypes))
	return nil
}

func declaration(locations []Location) Declaration {
	if len(locations) == 0 {
		return Declaration{Status: "no_local_predicate", Locations: []Location{}}
	}
	return Declaration{Status: "local_predicate_declared", Locations: locations}
}

func inspectDeclarations(known map[string]bool) (map[string][]Location, error) {
	paths, err := filepath.Glob(detectionGlob)
	if err != nil {
		return nil, err
	}
	if len(paths) == 0 {
		return nil, fmt.Errorf("no detection sources match %s; run from the repository root", detectionGlob)
	}
	result := make(map[string][]Location)
	pattern := regexp.MustCompile(unknownTypePattern)
	files := token.NewFileSet()
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(files, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		if ast.IsGenerated(file) {
			continue
		}
		ast.Inspect(file, func(node ast.Node) bool {
			literal, ok := node.(*ast.BasicLit)
			if !ok || literal.Kind != token.STRING {
				return true
			}
			value, err := strconv.Unquote(literal.Value)
			if err != nil || (!known[value] && !pattern.MatchString(value)) {
				return true
			}
			position := files.PositionFor(literal.Pos(), false)
			result[value] = append(result[value], Location{File: filepath.ToSlash(path), Line: position.Line, Column: position.Column})
			return true
		})
	}
	return result, nil
}

func gitOutput(dir string, args ...string) ([]byte, error) {
	command := exec.Command("git", append([]string{"-C", dir}, args...)...)
	output, err := command.Output()
	if err != nil {
		return nil, fmt.Errorf("read source Git provenance (%s): %w", strings.Join(args, " "), err)
	}
	return output, nil
}

func sourceProvenance(source string, data []byte) (Provenance, error) {
	absolute, err := filepath.Abs(source)
	if err != nil {
		return Provenance{}, err
	}
	dir := filepath.Dir(absolute)
	root, err := gitOutput(dir, "rev-parse", "--show-toplevel")
	if err != nil {
		return Provenance{}, err
	}
	relative, err := filepath.Rel(strings.TrimSpace(string(root)), absolute)
	if err != nil {
		return Provenance{}, err
	}
	relative = filepath.ToSlash(relative)
	repository, err := gitOutput(dir, "remote", "get-url", "origin")
	if err != nil {
		return Provenance{}, err
	}
	revision, err := gitOutput(dir, "rev-parse", "HEAD")
	if err != nil {
		return Provenance{}, err
	}
	committed, err := gitOutput(dir, "show", strings.TrimSpace(string(revision))+":"+relative)
	if err != nil {
		return Provenance{}, err
	}
	digest := sha256.Sum256(data)
	return Provenance{
		RepositoryURL:           strings.TrimSpace(string(repository)),
		Revision:                strings.TrimSpace(string(revision)),
		SourceFile:              relative,
		SourceSHA256:            hex.EncodeToString(digest[:]),
		SourceDiffersFromCommit: !bytes.Equal(committed, data),
	}, nil
}
