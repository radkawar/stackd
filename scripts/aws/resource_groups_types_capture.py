#!/usr/bin/env python3
"""Regenerate Resource Groups query eligibility from pinned AWS table rows.

Default generation is offline. --refresh captures the primary AWS Markdown page
and replaces the pinned rows; --markdown captures a previously downloaded page.
--check verifies that the generated Go source matches the pinned capture.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.request


ROOT = Path(__file__).resolve().parents[2]
SOURCE = 'https://docs.aws.amazon.com/ARG/latest/userguide/supported-resources.md'
FIXTURE = ROOT / 'testdata/aws/resourcegroups/supported_resource_types.json'
OUTPUT = ROOT / 'internal/services/resourcegroups/resource_types_generated.go'
COLUMNS = ['resource_type', 'tag_editor', 'tag_query', 'stack_query']


def rows_digest(rows):
    encoded = json.dumps(rows, separators=(',', ':'), ensure_ascii=True).encode()
    return hashlib.sha256(encoded).hexdigest()


def capture(source):
    rows = {}
    for line in source.decode('utf-8').splitlines():
        match = re.match(r'^\|\s*`(AWS::[^`]+)`\s*\|', line)
        if match is None:
            continue
        cells = line.split('|')[2:-1]
        if len(cells) != 3:
            raise ValueError(f'Expected three support columns: {line}')
        flags = []
        for cell in cells:
            flag = re.search(r'/icon-(yes|no)\.png\)\s*(Yes|No)', cell)
            if flag is None or flag[1].lower() != flag[2].lower():
                raise ValueError(f'Unrecognized support cell: {cell}')
            flags.append(flag[1] == 'yes')
        kind = match[1]
        if kind in rows and rows[kind] != flags:
            raise ValueError(f'Conflicting support rows for {kind}')
        rows[kind] = flags
    if not rows:
        raise ValueError('AWS support table contains no resource types')
    records = [[kind, *flags] for kind, flags in sorted(rows.items())]
    return {
        'source': SOURCE,
        'captured_at': datetime.now(timezone.utc).isoformat(),
        'source_sha256': hashlib.sha256(source).hexdigest(),
        'columns': COLUMNS,
        'rows_sha256': rows_digest(records),
        'rows': records,
    }


def render(captured):
    rows = captured['rows']
    if captured['source'] != SOURCE or captured['columns'] != COLUMNS:
        raise ValueError('Unexpected capture source or support columns')
    if not re.fullmatch(r'[0-9a-f]{64}', captured['source_sha256']):
        raise ValueError('Invalid captured source SHA256')
    if captured['rows_sha256'] != rows_digest(rows):
        raise ValueError('Pinned support rows SHA256 does not match')
    kinds = set()
    for row in rows:
        if (len(row) != 4 or not isinstance(row[0], str)
                or not re.fullmatch(r'AWS::[^:]+::[^:]+', row[0])
                or any(type(flag) is not bool for flag in row[1:])
                or row[0] in kinds):
            raise ValueError(f'Invalid pinned support row: {row}')
        kinds.add(row[0])
    text = '// Code generated by scripts/aws/resource_groups_types_capture.py; DO NOT EDIT.\n'
    text += f'// Source: {SOURCE}\n'
    text += f'// Source SHA256: {captured["source_sha256"]}\n'
    text += f'// Parsed rows SHA256: {captured["rows_sha256"]}\n'
    text += '// Offline input: testdata/aws/resourcegroups/supported_resource_types.json\n'
    text += '''
package resourcegroups

// ResourceTypeSupported reports AWS query eligibility, independently of whether
// a local owner currently exposes that resource type.
func ResourceTypeSupported(resourceType, queryType string) bool {
    var mask uint8
    switch queryType {
    case "TAG_FILTERS_1_0":
        mask = 1
    case "CLOUDFORMATION_STACK_1_0":
        mask = 2
    default:
        return false
    }
    return resourceTypeSupport[resourceType]&mask != 0
}

// Bits distinguish tag-query membership (1) from stack-query membership (2).
// Tag Editor support is retained in the fixture but does not decide membership.
var resourceTypeSupport = map[string]uint8{
'''
    for kind, _, tag, stack in sorted(rows):
        mode = int(tag) | (int(stack) << 1)
        if mode:
            text += '\t' + json.dumps(kind) + ': ' + str(mode) + ',\n'
    text += '}\n'
    return subprocess.run(['gofmt'], input=text, text=True, capture_output=True,
                          check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group()
    source.add_argument('--refresh', action='store_true', help='Capture the live primary AWS table')
    source.add_argument('--markdown', type=Path, help='Capture a previously downloaded primary page')
    parser.add_argument('--check', action='store_true', help='Check pinned generation without writing')
    args = parser.parse_args()
    if args.check and (args.refresh or args.markdown):
        parser.error('--check uses only the pinned fixture')
    if args.refresh or args.markdown:
        if args.markdown:
            raw = args.markdown.read_bytes()
        else:
            with urllib.request.urlopen(SOURCE, timeout=30) as response:
                raw = response.read()
        captured = capture(raw)
    else:
        captured = json.loads(FIXTURE.read_text())
    text = render(captured)
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('Resource Groups support source is stale; run this script without --check')
        print(f'Checked {len(captured["rows"])} pinned Resource Groups support rows')
        return
    if args.refresh or args.markdown:
        FIXTURE.write_text(json.dumps(captured, indent=2) + '\n')
    OUTPUT.write_text(text)
    print(f'Generated {len(captured["rows"])} Resource Groups support rows')
    print(f'Source SHA256: {captured["source_sha256"]}')
    print(f'Parsed rows SHA256: {captured["rows_sha256"]}')


if __name__ == '__main__':
    main()
