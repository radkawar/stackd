#!/usr/bin/env python3
"""Generate tag-policy resource validation data from AWS's published support table."""
import argparse
from html.parser import HTMLParser
from pathlib import Path
import re
import subprocess
import urllib.request

SOURCE = 'https://docs.aws.amazon.com/organizations/latest/userguide/orgs_manage_policies_supported-resources-enforcement.html'


class ResourceTable(HTMLParser):
    def __init__(self):
        super().__init__()
        self.rows, self.row, self.cell = [], None, None

    def handle_starttag(self, tag, attrs):
        if tag == 'tr': self.row = []
        if tag in ['td','th'] and self.row is not None: self.cell = []

    def handle_data(self, data):
        if self.cell is not None: self.cell.append(data)

    def handle_endtag(self, tag):
        if tag in ['td','th'] and self.cell is not None:
            self.row.append(' '.join(''.join(self.cell).split()))
            self.cell = None
        if tag == 'tr' and self.row is not None:
            self.rows.append(self.row)
            self.row = None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--html', type=Path, help='Use a previously downloaded AWS page')
    args = parser.parse_args()
    html = args.html.read_text() if args.html else urllib.request.urlopen(SOURCE).read().decode()
    table = ResourceTable()
    table.feed(html)
    resources = {}
    for row in table.rows:
        if len(row) < 6: continue
        key = next((cell for cell in row[:-4] if re.fullmatch(r'[a-z0-9-]+:[A-Za-z0-9_./*-]+', cell)), None)
        if key is None: continue
        # The last columns are basic reporting, basic enforcement, required
        # reporting, and IaC enforcement. This consumer validates the two public
        # policy fields; the IaC integration owns its eventual execution seam.
        mode = int(row[-3] == 'Yes') | (int(row[-2] == 'Yes') << 1)
        if mode: resources[key] = mode
    if not resources: raise RuntimeError('AWS support table contains no usable resource rows')
    text = '// Code generated by scripts/aws/tag_policy_resources_capture.py; DO NOT EDIT.\n// Source: '+SOURCE+'\n\npackage organizations\n\nvar tagPolicyResourceModes = map[string]uint8{\n'
    for key, mode in sorted(resources.items()):
        value = {1:'tagEnforcement',2:'tagRequiredReporting',3:'tagEnforcement | tagRequiredReporting'}[mode]
        text += '\t"'+key+'": '+value+',\n'
    text += '}\n'
    path = Path('internal/services/organizations/tag_policy_resources_generated.go')
    path.write_text(text)
    subprocess.run(['gofmt','-w',str(path)],check=True)
    print(f'Generated {len(resources)} tag-policy resource entries')

if __name__ == '__main__': main()
