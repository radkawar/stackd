#!/usr/bin/env python3
"""Capture required-tag resource types and exact CloudFormation aliases from AWS."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

from tag_policy_resources_capture import ResourceTable, SOURCE


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--html', type=Path, help='Use a previously downloaded AWS page')
    args = parser.parse_args()
    html = args.html.read_text() if args.html else urllib.request.urlopen(SOURCE).read().decode()
    table = ResourceTable()
    table.feed(html)
    aliases = {}
    wildcards = set()
    for row in table.rows:
        if len(row) < 6 or row[-2] != 'Yes':
            continue
        key_index = next((i for i, cell in enumerate(row[:-4])
                          if re.fullmatch(r'[a-z0-9-]+:[A-Za-z0-9_./*-]+', cell)), None)
        if key_index is None:
            continue
        key = row[key_index]
        if key.endswith(':ALL_SUPPORTED'):
            wildcards.add(key)
            continue
        cell = row[key_index + 1]
        types = re.findall(r'AWS::[A-Za-z0-9]+::[A-Za-z0-9]+', cell)
        if not types and cell != 'N/A':
            raise ValueError(f'Unrecognized CloudFormation aliases for {key}: {cell}')
        aliases.setdefault(key, set()).update(types)
    if not aliases:
        raise ValueError('AWS support table contains no required-reporting resource types')
    # The map is consumed directly, including multi-alias rows and documented N/A.
    text = '// Code generated by scripts/aws/resource_tagging_cfn_capture.py; DO NOT EDIT.\n'
    text += f'// Source: {SOURCE}\n// Source SHA256: {hashlib.sha256(html.encode()).hexdigest()}\n\n'
    text += 'package integrations\n\nvar resourceTaggingCloudFormationTypes = map[string][]string{\n'
    for key, values in sorted(aliases.items()):
        text += '\t' + json.dumps(key) + ': {' + ', '.join(json.dumps(v) for v in sorted(values)) + '},\n'
    text += '}\n\nvar resourceTaggingRequiredTypeWildcards = map[string][]string{\n'
    for key in sorted(wildcards):
        prefix = key.split(':')[0] + ':'
        values = [k for k in sorted(aliases) if k.startswith(prefix)]
        if not values:
            raise ValueError(f'Required-reporting wildcard has no documented types: {key}')
        text += '\t' + json.dumps(key) + ': {' + ', '.join(json.dumps(v) for v in values) + '},\n'
    text += '}\n'
    path = Path('internal/integrations/resource_tagging_cfn_generated.go')
    path.write_text(text)
    print(f'Captured {len(aliases)} required-reporting types and {len(wildcards)} service wildcards')
    print('ec2:instance:', sorted(aliases['ec2:instance']))
    print('s3:bucket:', sorted(aliases['s3:bucket']))
    print('rds:db:', sorted(aliases['rds:db']))


if __name__ == '__main__':
    main()
