#!/usr/bin/env python3
"""Generate typed RDS/DocumentDB Query projections from the pinned Smithy models."""
import argparse
import json
from pathlib import Path
import subprocess


def generate(sdk, destination, check):
    base = sdk / "codegen/sdk-codegen/aws-models"
    models = {name: json.loads((base / (name + ".json")).read_text())["shapes"] for name in ("rds", "docdb")}
    operations = {name: {key.split("#")[1]: value for key, value in shapes.items() if value["type"] == "operation"}
                  for name, shapes in models.items()}
    common = sorted(operations["rds"].keys() & operations["docdb"].keys())
    generated, pending = {}, []
    def shape(service, target):
        if target == "smithy.api#Unit":
            return {"type": "structure", "members": {}}
        return models[service][target]
    def name(target):
        return target.split("#")[1]
    def request(source, target, src, dst):
        key = (source, target, src, dst)
        function = source + "To" + target.title() + name(src) + "As" + name(dst)
        if key not in generated:
            generated[key] = function
            pending.append(key)
        return function
    lines = ["// Code generated by scripts/generate_docdb_query.py; DO NOT EDIT.",
             "// Source: aws-sdk-go-v2 " + subprocess.check_output(["git", "-C", str(sdk), "rev-parse", "HEAD"], text=True).strip(),
             "package integrations", "", "import (", ' "fmt"', ' "stackd/internal/awsapi"',
             ' docdbapi "stackd/internal/awsapi/docdb"', ' rdsapi "stackd/internal/awsapi/rds"', ' "stackd/internal/awscatalog"', ")", ""]
    lines += ["func documentDBCommand(in awsapi.DecodedRequest)(awsapi.DecodedRequest,error){", ' model,_:=awscatalog.LookupService("docdb")',
              " operation,ok:=model.Operation(string(in.Operation.Name));if !ok{return awsapi.DecodedRequest{},fmt.Errorf(\"operation is not a DocumentDB contract\")}",
              " out:=awsapi.DecodedRequest{Operation:operation,Protocol:in.Protocol}", " switch string(in.Operation.Name){"]
    for op in common:
        src = operations["rds"][op].get("input", {"target": "smithy.api#Unit"})["target"]
        dst = operations["docdb"][op].get("input", {"target": "smithy.api#Unit"})["target"]
        convert = request("rds", "docdb", src, dst)
        lines += [f' case "{op}":', f'  value,ok:=in.Input.(*rdsapi.{name(src)});if !ok{{return out,fmt.Errorf("invalid {op} input")}}',
                  f'  converted,err:={convert}(*value);if err!=nil{{return out,err}};out.Input=&converted']
    lines += [' default:return out,fmt.Errorf("operation is not a shared Query contract")', ' };return out,nil', '}']
    lines += ['func documentDBOutput(action string,in any)(any,error){switch action{']
    for op in common:
        src = operations["docdb"][op].get("output", {"target": "smithy.api#Unit"})["target"]
        dst = operations["rds"][op].get("output", {"target": "smithy.api#Unit"})["target"]
        convert = request("docdb", "rds", src, dst)
        lines += [f'case "{op}": value,ok:=in.(*docdbapi.{name(src)});if !ok{{return nil,fmt.Errorf("invalid {op} output")}};converted,err:={convert}(*value);return &converted,err']
    lines += ['default:return nil,fmt.Errorf("operation is not a shared Query contract")}}']
    while pending:
        source, target, src, dst = pending.pop(0)
        source_shape, target_shape = shape(source, src), shape(target, dst)
        kind = source_shape["type"]
        if kind != target_shape["type"]:
            raise ValueError((src, dst, kind, target_shape["type"]))
        function = generated[(source, target, src, dst)]
        lines += [f'func {function}(in {source}api.{name(src)})({target}api.{name(dst)},error){{', f'var out {target}api.{name(dst)}']
        if kind == "structure":
            for field, member in source_shape.get("members", {}).items():
                st = member["target"]
                if field not in target_shape.get("members", {}):
                    lines += [f'if in.{field}!=nil{{return out,fmt.Errorf("field {field} is not supported by the {target} contract")}}']
                    continue
                dt = target_shape["members"][field]["target"]
                member_kind = shape(source, st)["type"]
                if member_kind == "structure":
                    convert = request(source, target, st, dt)
                    lines += [f'if in.{field}!=nil{{converted,err:={convert}(*in.{field});if err!=nil{{return out,err}};out.{field}=&converted}}']
                elif member_kind in ("list", "map"):
                    convert = request(source, target, st, dt)
                    lines += [f'if in.{field}!=nil{{converted,err:={convert}(in.{field});if err!=nil{{return out,err}};out.{field}=converted}}']
                else:
                    lines += [f'out.{field}=(*{target}api.{name(dt)})(in.{field})']
        elif kind == "list":
            st, dt = source_shape["member"]["target"], target_shape["member"]["target"]
            lines += ['if in==nil{return nil,nil}', f'out=make({target}api.{name(dst)},len(in))', 'for i,value:=range in{']
            if shape(source, st)["type"] in ("structure", "list", "map"):
                convert = request(source, target, st, dt)
                lines += [f'converted,err:={convert}(value);if err!=nil{{return nil,err}};out[i]=converted']
            else:
                lines += [f'out[i]={target}api.{name(dt)}(value)']
            lines += ['}']
        else:
            raise ValueError((src, dst, kind))
        lines += ['return out,nil', '}']
    body = subprocess.check_output(["gofmt"], input="\n".join(lines) + "\n", text=True)
    if check:
        if destination.read_text() != body:
            raise SystemExit("DocumentDB Query projections are stale; run make generate-aws")
    else:
        destination.write_text(body)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("internal/integrations/docdb_query_generated.go"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(args.sdk, args.output, args.check)
