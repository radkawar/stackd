package iam

import "time"

// AccountMetadata records the local account's provisioning time independently
// of its credentials and report generation. An absent record is distinct from
// a record whose creation time is the zero epoch.
type AccountMetadata struct {
	CreatedAt time.Time
}

// CredentialReportState describes stored work, independently of the API's
// STARTED response for accepting a new generation request.
type CredentialReportState string

const (
	CredentialReportPending  CredentialReportState = "pending"
	CredentialReportComplete CredentialReportState = "complete"
	CredentialReportFailed   CredentialReportState = "failed"
)

// CredentialReportRecord is both the account's generation intent and immutable
// completed CSV artifact. Generation fences stale workers; Content belongs to
// this snapshot and must never be regenerated by a Get request.
type CredentialReportRecord struct {
	Generation  uint64
	State       CredentialReportState
	RequestedAt time.Time
	GeneratedAt time.Time
	Content     []byte
}
