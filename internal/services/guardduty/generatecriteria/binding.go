package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"slices"
)

// binding emits mutations of an already-owned clone. Model-derived traversal is
// generated once, never reflected or JSON-roundtripped for individual findings.
type binding struct {
	model   *generator
	structs map[string]string
	serial  int
}

func (b *binding) emit(e ast.Expr, expr string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if t.Name == "string" {
			return "mapFindingString(" + bindingAddress(expr) + ", mapString)\n"
		}
		underlying, ok := b.model.types[t.Name]
		if !ok {
			return ""
		}
		if _, ok := underlying.(*ast.StructType); ok {
			if _, seen := b.structs[t.Name]; !seen {
				b.structs[t.Name] = ""
				b.structs[t.Name] = b.emit(underlying, "(*v)")
			}
			if b.structs[t.Name] == "" {
				return ""
			}
			return "mapFinding" + t.Name + "Strings(" + bindingAddress(expr) + ", mapString)\n"
		}
		return b.emit(underlying, expr)
	case *ast.StarExpr:
		body := b.emit(t.X, "(*"+expr+")")
		if body == "" {
			return ""
		}
		return "if " + expr + " != nil {\n" + body + "}\n"
	case *ast.StructType:
		var body string
		for _, f := range t.Fields.List {
			for _, name := range f.Names {
				body += b.emit(f.Type, expr+"."+name.Name)
			}
		}
		return body
	case *ast.ArrayType:
		b.serial++
		index := fmt.Sprintf("i%d", b.serial)
		body := b.emit(t.Elt, expr+"["+index+"]")
		if body == "" {
			return ""
		}
		return "for " + index + " := range " + expr + " {\n" + body + "}\n"
	case *ast.MapType:
		b.serial++
		k, v := fmt.Sprintf("k%d", b.serial), fmt.Sprintf("v%d", b.serial)
		body := b.emit(t.Value, v)
		if body == "" {
			return ""
		}
		return "for " + k + ", " + v + " := range " + expr + " {\n" + body + expr + "[" + k + "] = " + v + "\n}\n"
	}
	return ""
}

// bindingAddress cancels an outer dereference when passing an owned pointer.
func bindingAddress(expr string) string {
	node, err := parser.ParseExpr(expr)
	if err != nil {
		panic(err)
	}
	for {
		if paren, ok := node.(*ast.ParenExpr); ok {
			node = paren.X
		} else {
			break
		}
	}
	if star, ok := node.(*ast.StarExpr); ok {
		var out bytes.Buffer
		if err := format.Node(&out, token.NewFileSet(), star.X); err != nil {
			panic(err)
		}
		return out.String()
	}
	return "&" + expr
}

func (g *generator) generateBinding() {
	b := binding{model: g, structs: map[string]string{}}
	root := b.emit(ast.NewIdent("Finding"), "(*f)")
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./generatecriteria; DO NOT EDIT.\npackage guardduty\nimport api \"stackd/internal/awsapi/guardduty\"\n")
	fmt.Fprintf(&out, "func mapFindingStrings(f *api.Finding, mapString func(string) string) { if f != nil {\n%s} }\n", root)
	out.WriteString("func mapFindingString[T ~string](v *T, mapString func(string) string) { *v = T(mapString(string(*v))) }\n")
	for _, name := range slices.Sorted(maps.Keys(b.structs)) {
		body := b.structs[name]
		if body == "" {
			continue
		}
		fmt.Fprintf(&out, "func mapFinding%sStrings(v *api.%s, mapString func(string) string) {\n%s}\n", name, name, body)
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("sample_bind_generated.go", source, 0644); err != nil {
		panic(err)
	}
}
