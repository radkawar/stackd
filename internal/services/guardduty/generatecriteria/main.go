// Command generatecriteria derives typed finding selectors from the generated SDK model.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"strconv"
	"strings"
)

type generator struct {
	types  map[string]ast.Expr
	serial int
}

func (g *generator) resolve(e ast.Expr) ast.Expr {
	if id, ok := e.(*ast.Ident); ok {
		if v, ok := g.types[id.Name]; ok {
			return g.resolve(v)
		}
	}
	return e
}
func (g *generator) emit(e ast.Expr, expr string, parts []string, timestamp bool) (string, string, bool) {
	e = g.resolve(e)
	switch t := e.(type) {
	case *ast.StarExpr:
		body, kind, ok := g.emit(t.X, "(*"+expr+")", parts, timestamp)
		return "if " + expr + " != nil {\n" + body + "}\n", kind, ok
	case *ast.ArrayType:
		g.serial++
		n := fmt.Sprintf("v%d", g.serial)
		body, kind, ok := g.emit(t.Elt, n, parts, timestamp)
		return "for _, " + n + " := range " + expr + " {\n" + body + "}\n", kind, ok
	case *ast.StructType:
		if len(parts) == 0 {
			return "", "", false
		}
		for _, f := range t.Fields.List {
			if f.Tag == nil {
				continue
			}
			tag, _ := strconv.Unquote(f.Tag.Value)
			name := strings.Split(reflect.StructTag(tag).Get("json"), ",")[0]
			if strings.EqualFold(name, parts[0]) {
				return g.emit(f.Type, expr+"."+f.Names[0].Name, parts[1:], timestamp)
			}
		}
	case *ast.SelectorExpr:
		if len(parts) == 0 && t.Sel.Name == "Time" {
			return "if visit(findingValue{kind: findingNumber, number: float64(" + expr + ".UnixMilli())}) { return true }\n", "findingNumber", true
		}
	case *ast.Ident:
		if len(parts) != 0 {
			return "", "", false
		}
		val, kind := "", ""
		switch t.Name {
		case "string":
			kind = "findingString"
			val = "findingValue{kind: findingString, text: string(" + expr + ")}"
			if timestamp {
				kind = "findingNumber"
				val = "findingTimestamp(string(" + expr + "))"
			}
		case "bool":
			kind = "findingBool"
			val = "findingBoolean(bool(" + expr + "))"
		case "float64", "float32", "int32", "int64", "int":
			kind = "findingNumber"
			val = "findingValue{kind: findingNumber, number: float64(" + expr + ")}"
		}
		if val != "" {
			return "if visit(" + val + ") { return true }\n", kind, true
		}
	}
	return "", "", false
}
func main() {
	f, err := parser.ParseFile(token.NewFileSet(), "../../awsapi/guardduty/types_generated.go", nil, 0)
	if err != nil {
		panic(err)
	}
	g := generator{types: map[string]ast.Expr{}}
	for _, d := range f.Decls {
		if gd, ok := d.(*ast.GenDecl); ok {
			for _, sp := range gd.Specs {
				if ts, ok := sp.(*ast.TypeSpec); ok {
					g.types[ts.Name.Name] = ts.Type
				}
			}
		}
	}
	manifest, err := os.Open("criteria_fields.txt")
	if err != nil {
		panic(err)
	}
	defer manifest.Close()
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./generatecriteria; DO NOT EDIT.\npackage guardduty\n\nimport api \"stackd/internal/awsapi/guardduty\"\n\nvar findingSelectors = map[string]findingSelector{\n")
	scanner := bufio.NewScanner(manifest)
	seen := make(map[string]bool)
	for scanner.Scan() {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		path := fields[0]
		if seen[path] {
			fmt.Fprintf(os.Stderr, "Duplicate criterion selector: %s\n", path)
			os.Exit(1)
		}
		seen[path] = true
		body, kind, ok := g.emit(ast.NewIdent("Finding"), "f", strings.Split(path, "."), len(fields) > 1)
		if !ok && strings.HasPrefix(path, "service.additionalInfo.") {
			kind = "findingDynamic"
			body = fmt.Sprintf("return visitAdditionalInfo(f, %q, visit)\n", strings.TrimPrefix(path, "service.additionalInfo."))
			fmt.Fprintf(&b, "%q: {kind: %s, visit: func(f api.Finding, visit func(findingValue) bool) bool {\n%s}},\n", path, kind, body)
			continue
		}
		if !ok {
			// TODO: Comeback project documented selectors absent from the pinned
			// Finding model once their authoritative typed contracts are available.
			fmt.Fprintf(os.Stderr, "Unsupported model selector: %s\n", path)
			continue
		}
		fmt.Fprintf(&b, "%q: {kind: %s, visit: func(f api.Finding, visit func(findingValue) bool) bool {\n%s return false\n}},\n", path, kind, body)
	}
	if err := scanner.Err(); err != nil {
		panic(err)
	}
	b.WriteString("}\n")
	source, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("criteria_fields_generated.go", source, 0644); err != nil {
		panic(err)
	}
	g.generateBinding()
}
